        return HasActivePair(portal);
    }

    /// <summary>
    /// Applies the same entry-to-exit pose transform used by player movement.
    /// </summary>
    public static void TransformPortalPose(
        Portal entry,
        Portal exit,
        Vector3 position,
        Quaternion rotation,
        out Vector3 transformedPosition,
        out Quaternion transformedRotation)
    {
        if (!HasActivePair(entry) || exit != entry.otherPortal)
        {
            transformedPosition = position;
            transformedRotation = rotation;
            return;
        }

        Quaternion portalRotation = GetPortalRotation(entry, exit);
        transformedPosition = MapPortalPoint(entry, exit, position);
        transformedRotation = portalRotation * rotation;
    }

    /// <summary>
    /// Detects a portalable object's swept bounds crossing the portal plane
    /// and opening. If Item-layer registration missed the crossing, portal
    /// ownership can recover the object while it remains inside the carved
    /// recess. Local physics and portal-space sweeps resolve world contacts.
    /// </summary>
    public static bool TryHandlePortalableObjectMovement(
        Vector3 previousBoundsCenter,
        Vector3 currentBoundsCenter,
        Vector3 boundsHalfExtents,
        Portal portalEnvironment,
        Portal recentlyExitedPortal,
        ref Vector3 objectPosition,
        ref Quaternion objectRotation,
        out Portal entryPortal,
        out Portal exitPortal,
        out Quaternion portalRotation,
        out float crossingFraction)
    {
        entryPortal = null;
        exitPortal = null;
        portalRotation = Quaternion.identity;
        crossingFraction = 0f;

        float nearestFraction = float.PositiveInfinity;
        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal candidate = ActivePortals[i];
            if (!HasActivePair(candidate))
                continue;

            Vector3 normal = GetPortalPlaneNormal(candidate);
            float startDistance = Vector3.Dot(
                previousBoundsCenter - candidate.transform.position, normal);
            float endDistance = Vector3.Dot(
                currentBoundsCenter - candidate.transform.position, normal);

            float normalExtent = ProjectHalfExtent(
                normal,
                Vector3.right,
                Vector3.up,
                Vector3.forward,
                boundsHalfExtents);
            if (candidate == recentlyExitedPortal &&
                endDistance <= PortalableObjectExitClearance + normalExtent)
                continue;

            float distanceTravelled = startDistance - endDistance;
            bool crossedPlane = startDistance > 0.000001f &&
                endDistance <= 0f && distanceTravelled > 0.000001f;
            float missedCrossingDepth = normalExtent +
                GetPortalRecessDepthWorld(candidate, SourcePlayerHalfHeightHu) +
                PlayerCutoutTolerance;
            bool recoveringMissedCrossing =
                candidate == portalEnvironment &&
                endDistance <= 0f &&
                endDistance >= -missedCrossingDepth;
            if (endDistance > 0f ||
                (!crossedPlane && !recoveringMissedCrossing))
                continue;

            // Item-layer registration can happen after a fast physics step
            // has already carried the object into the carved recess. Source
            // keeps portal ownership while an entity is touching the portal;
            // use that ownership to recover the missed centre crossing once,
            // before the object reaches the blind-recess back cap.
            float fraction = crossedPlane
                ? startDistance / distanceTravelled
                : 1f;
            if (fraction < 0f || fraction > 1f ||
                fraction >= nearestFraction)
                continue;

            Vector3 centerAtPlane = crossedPlane
                ? Vector3.Lerp(
                    previousBoundsCenter, currentBoundsCenter, fraction)
                : currentBoundsCenter - normal * endDistance;
            // Use the exact same overlap gate as player movement. The carved
            // wall decides whether the object's real collider can reach the
            // portal plane; requiring its conservative world AABB to fit the
            // entire aperture rejects valid floor crossings and lets physics
            // continue through the carved floor without teleporting.
            if (!IsHullInsidePortalOpening(
                candidate, centerAtPlane, boundsHalfExtents))
                continue;

            nearestFraction = fraction;
            entryPortal = candidate;
        }

        if (entryPortal == null)
            return false;

        exitPortal = entryPortal.otherPortal;
        portalRotation = GetPortalRotation(entryPortal, exitPortal);
        crossingFraction = nearestFraction;
        objectPosition = MapPortalPoint(
            entryPortal, exitPortal, objectPosition);
        objectRotation = portalRotation * objectRotation;
        return true;
    }

    /// <summary>
    /// Runs the Source-style remote collision sweep for a portalable object.
    /// While an object is touching an entry portal, Source simulates its
    /// collision hull in the linked portal's world and maps the first contact
    /// back to the object's current world. This lets a prop slide or stop on
    /// remote geometry before its centre crosses the portal plane.
    /// </summary>
    public static bool TryGetPortalableObjectSpaceCollision(
        Vector3 center,
        Vector3 boundsHalfExtents,
        Vector3 sweepDelta,
        int layerMask,
        Transform movingRoot,
        Portal recentlyExitedPortal,
        out RaycastHit nearest)
    {
        nearest = default;
        if (sweepDelta.sqrMagnitude <= 0.000001f)
            return false;

        bool found = false;
        float firstPortalFraction = float.PositiveInfinity;
        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal entry = ActivePortals[i];
            if (entry == recentlyExitedPortal)
                continue;

            RaycastHit candidate;
            float crossingFraction;
            bool crossesPortal;
            bool hasRemoteHit =
                TryGetPortalableObjectSpaceCollisionThroughPortal(
                    entry,
                    center,
                    boundsHalfExtents,
                    sweepDelta,
                    layerMask,
                    movingRoot,
                    out candidate,
                    out crossingFraction,
                    out crossesPortal,
                    false);
            if (!crossesPortal || crossingFraction >= firstPortalFraction)
                continue;

            // One movement sample can intersect several nearby portal planes.
            // The movement solver teleports through only the first one, so a
            // remote hit from a later portal is a different hypothetical path.
            firstPortalFraction = crossingFraction;
            found = hasRemoteHit;
            nearest = hasRemoteHit ? candidate : default;
        }

        return found;
    }

    /// <summary>
    /// Sweeps a moving hull through an entry portal against colliders in the
    /// linked world. The nearest hit is returned in entry-space so the caller
    /// can resolve the remote contact as a local collision.
    /// </summary>
    private static bool TryGetPortalableObjectSpaceCollisionThroughPortal(
        Portal entry,
        Vector3 center,
        Vector3 boundsHalfExtents,
        Vector3 sweepDelta,
        int layerMask,
        Transform movingRoot,
        out RaycastHit nearest,
        out float portalCrossingFraction,
        out bool crossesPortal,
        bool portalableObjectsOnly)
    {
        nearest = default;
        portalCrossingFraction = float.PositiveInfinity;
        crossesPortal = false;
        if (!HasActivePair(entry))
            return false;

        float localDistance = sweepDelta.magnitude;
        if (localDistance <= 0.000001f)
            return false;

        Vector3 normal = GetPortalPlaneNormal(entry);
        float startDistance = Vector3.Dot(
            center - entry.transform.position, normal);
        float deltaDistance = Vector3.Dot(sweepDelta, normal);
        float normalExtent = ProjectHalfExtent(
            normal,
            Vector3.right,
            Vector3.up,
            Vector3.forward,
            boundsHalfExtents);
        if (deltaDistance >= -0.000001f ||
            startDistance < -normalExtent - PlayerCutoutTolerance ||
            startDistance + deltaDistance > normalExtent)
            return false;

        float planeFraction = Mathf.Clamp01(startDistance / -deltaDistance);
        Vector3 centerAtPlane = center + sweepDelta * planeFraction;
        if (!FitsPortalOpening(
                entry,
                centerAtPlane,
                boundsHalfExtents,
                Quaternion.identity,
                SourcePortalBottomCarve))
            return false;

        portalCrossingFraction = planeFraction;
        crossesPortal = true;

        Portal exit = entry.otherPortal;
        Quaternion portalRotation = GetPortalRotation(entry, exit);
        Vector3 remoteHalfExtents = TransformAabbHalfExtents(
            boundsHalfExtents, portalRotation);
        Vector3 remoteCenterAtPlane = MapPortalPoint(
            entry, exit, centerAtPlane);
        if (!FitsPortalOpening(
                exit,
                remoteCenterAtPlane,
                remoteHalfExtents,
                Quaternion.identity,
                SourcePortalBottomCarve))
            return false;

        float remoteNormalExtent = ProjectHalfExtent(
            GetPortalPlaneNormal(exit),
            Vector3.right,
            Vector3.up,
            Vector3.forward,
            remoteHalfExtents);
        Vector3 remoteShift = GetPortalPlaneNormal(exit) *
            (remoteNormalExtent - normalExtent);
        Vector3 remoteStart = MapPortalPoint(entry, exit, center) +
            remoteShift;
        Vector3 remoteDelta = portalRotation * sweepDelta;
        float remoteDistance = remoteDelta.magnitude;
        if (remoteDistance <= 0.000001f)
            return false;

        int hitCount;
        while (true)
        {
            hitCount = Physics.BoxCastNonAlloc(
                remoteStart,
                remoteHalfExtents,
                remoteDelta / remoteDistance,
                portalMovementHits,
                Quaternion.identity,
                remoteDistance,
                layerMask,
                QueryTriggerInteraction.Ignore);
            if (hitCount < portalMovementHits.Length)
                break;

            System.Array.Resize(
                ref portalMovementHits,
                portalMovementHits.Length * 2);
        }

        Vector3 remoteEnd = remoteStart + remoteDelta;
        bool found = false;
        float nearestDistance = float.PositiveInfinity;
        for (int i = 0; i < hitCount; ++i)
        {
            RaycastHit hit = portalMovementHits[i];
            Collider collider = hit.collider;
            if (collider == null ||
                IsPortalOwnedCollider(collider) ||
                (portalableObjectsOnly &&
                 collider.GetComponentInParent<PortalableObject>() == null) ||
                (movingRoot != null &&
                 (collider.transform == movingRoot ||
                  collider.transform.IsChildOf(movingRoot))))
                continue;

            // Source discards a remote trace that begins inside world
            // geometry. This commonly occurs where a floor exit meets its
            // host wall; after teleport, Unity's normal contact solver owns
            // that overlap.
            if (hit.distance <= RemoteStartSolidEpsilon)
                continue;

            if (IsPortalWallAtRemoteOpening(
                    hit,
                    exit,
                    remoteStart,
                    remoteHalfExtents,
                    Quaternion.identity,
                    remoteEnd))
                continue;

            float distance = hit.distance * (localDistance / remoteDistance);
            if (distance >= nearestDistance)
                continue;

            hit.distance = distance;
            hit.normal = Quaternion.Inverse(portalRotation) * hit.normal;
            hit.point = MapPortalPoint(
                exit,
                entry,
                hit.point - remoteShift);
            nearest = hit;
            nearestDistance = distance;
            found = true;
        }

        return found;
    }

    public static Vector3 TransformAabbHalfExtents(
        Vector3 halfExtents,
        Quaternion rotation)
    {
        Vector3 right = rotation * Vector3.right;
        Vector3 up = rotation * Vector3.up;
        Vector3 forward = rotation * Vector3.forward;
        return new Vector3(
            Mathf.Abs(right.x) * halfExtents.x +
                Mathf.Abs(up.x) * halfExtents.y +
                Mathf.Abs(forward.x) * halfExtents.z,
            Mathf.Abs(right.y) * halfExtents.x +
                Mathf.Abs(up.y) * halfExtents.y +
                Mathf.Abs(forward.y) * halfExtents.z,
            Mathf.Abs(right.z) * halfExtents.x +
                Mathf.Abs(up.z) * halfExtents.y +
                Mathf.Abs(forward.z) * halfExtents.z);
    }

    /// <summary>
    /// Source traces the movement hull through the entry portal and into the
    /// linked portal's remote world. Return the remote hit in entry-space so
    /// the normal Source slide solver can resolve it as an ordinary collision.
    /// </summary>
    public static bool TryGetPortalSpaceCollision(
        Vector3 center,
        Vector3 hullHalfExtents,
        Vector3 duckHullHalfExtents,
        Quaternion hullRotation,
        Vector3 movementUp,
        Vector3 sweepDelta,
        int layerMask,
        Transform movingRoot,
        out RaycastHit nearest,
        out bool contactedTransitionRamp)
    {
        nearest = default;
        contactedTransitionRamp = false;
        if (sweepDelta.magnitude <= 0.000001f)
            return false;

        float nearestDistance = float.PositiveInfinity;
        bool found = false;
        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal entry = ActivePortals[i];
            RaycastHit candidate;
            bool ramp;
            bool hitFound = TryGetPortalSpaceCollisionThroughPortal(
                entry,
                center,
                hullHalfExtents,
                duckHullHalfExtents,
                hullRotation,
                movementUp,
                sweepDelta,
                layerMask,
                movingRoot,
                out candidate,
                out ramp);
            if (ramp)
                contactedTransitionRamp = true;
            if (!hitFound)
                continue;
            if (candidate.distance >= nearestDistance)
                continue;

            nearest = candidate;
            contactedTransitionRamp = ramp;
            nearestDistance = candidate.distance;
            found = true;
        }
        return found;
    }

    /// <summary>
    /// Source uses the player's m_hPortalEnvironment as the single portal
    /// environment for the trace. Use that exact portal instead of scanning
    /// every active portal pair.
    /// </summary>
    public static bool TryGetPortalSpaceCollision(
        Portal environment,
        Vector3 center,
        Vector3 hullHalfExtents,
        Vector3 duckHullHalfExtents,
        Quaternion hullRotation,
        Vector3 movementUp,
        Vector3 sweepDelta,
        int layerMask,
        Transform movingRoot,
        out RaycastHit nearest,
        out bool contactedTransitionRamp)
    {
        nearest = default;
        contactedTransitionRamp = false;
        if (environment == null || sweepDelta.magnitude <= 0.000001f)
            return false;
        return TryGetPortalSpaceCollisionThroughPortal(
            environment,
            center,
            hullHalfExtents,
            duckHullHalfExtents,
            hullRotation,
            movementUp,
            sweepDelta,
            layerMask,
            movingRoot,
            out nearest,
            out contactedTransitionRamp);
    }

    private static bool TryGetPortalSpaceCollisionThroughPortal(
        Portal entry,
        Vector3 center,
        Vector3 hullHalfExtents,
        Vector3 duckHullHalfExtents,
        Quaternion hullRotation,
        Vector3 movementUp,
        Vector3 sweepDelta,
        int layerMask,
        Transform movingRoot,
        out RaycastHit nearest,
        out bool contactedTransitionRamp)
    {
        nearest = default;
        contactedTransitionRamp = false;

        // Remote pre-simulation is deliberately off. The teleport now lands
        // the hull at the exit portal's centre, so a box cast mapped from the
        // incoming position tests a path the player never takes. Worse, the
        // mapped hull starts embedded in the exit wall on floor->wall pairs;
        // BoxCastNonAlloc reports distance 0 there and the slide solver pins
        // the player on the entry side. That is the "sinks into the floor
        // portal without teleporting" symptom. Local collision remains in
        // authority until the centre crosses the plane, after which normal
        // collision at the exit centre takes over.
        if (!s_remotePreSimulationEnabled || !HasActivePair(entry))
            return false;

        float localDistance = sweepDelta.magnitude;
        if (localDistance <= 0.000001f)
            return false;

        Vector3 normal = GetPortalPlaneNormal(entry);
        float startDistance = Vector3.Dot(
            center - entry.transform.position, normal);
        float deltaDistance = Vector3.Dot(sweepDelta, normal);
        float normalExtent = ProjectHalfExtent(
            normal,
            hullRotation * Vector3.right,
            hullRotation * Vector3.up,
            hullRotation * Vector3.forward,
            hullHalfExtents);

        // The sweep must approach the portal from its front and reach the
        // portal plane with some part of the hull during this command.
        if (deltaDistance >= -0.000001f ||
            startDistance < -normalExtent - PlayerCutoutTolerance ||
            startDistance + deltaDistance > normalExtent)
            return false;

        float planeFraction = Mathf.Clamp01(
            startDistance / -deltaDistance);
        Vector3 centerAtPlane = center + sweepDelta * planeFraction;
        // Source's remote tube check requires the player to fit through the
        // aperture in both configurations, not merely intersect it.
        if (!FitsPortalOpening(
                entry, centerAtPlane, hullHalfExtents, hullRotation,
                SourcePortalBottomCarve))
            return false;

        Portal exit = entry.otherPortal;
        Quaternion portalRotation = GetPortalRotation(entry, exit);
        bool transitionNeedsDuck = ShouldForcePortalCrouch(
            entry, movementUp, hullHalfExtents, duckHullHalfExtents);
        Vector3 remoteHalfExtents = transitionNeedsDuck
            ? duckHullHalfExtents
            : hullHalfExtents;
        Vector3 remoteCenterAtPlane = MapPortalPoint(
            entry, exit, centerAtPlane);
        if (!FitsPortalOpening(
                exit, remoteCenterAtPlane, remoteHalfExtents, hullRotation,
                SourcePortalBottomCarve))
            return false;

        float remoteNormalExtent = ProjectHalfExtent(
            GetPortalPlaneNormal(exit),
            hullRotation * Vector3.right,
            hullRotation * Vector3.up,
            hullRotation * Vector3.forward,
            remoteHalfExtents);
        float extentDifference = remoteNormalExtent - normalExtent;
        Vector3 remoteShift = GetPortalPlaneNormal(exit) * extentDifference;
        Vector3 remoteStart = MapPortalPoint(entry, exit, center) +
            remoteShift;
        Vector3 remoteDelta = portalRotation * sweepDelta;
        float remoteDistance = remoteDelta.magnitude;
        if (remoteDistance <= 0.000001f)
            return false;

        bool rampContact = TryGetTransitionRampContact(
            exit,
            remoteStart,
            remoteDelta,
            remoteHalfExtents,
            out float rampFraction);

        int hitCount;
        while (true)
        {
            hitCount = Physics.BoxCastNonAlloc(
                remoteStart,
                remoteHalfExtents,
                remoteDelta / remoteDistance,
                portalMovementHits,
                Quaternion.identity,
                remoteDistance,
                layerMask,
                QueryTriggerInteraction.Ignore);
            if (hitCount < portalMovementHits.Length)
                break;

            System.Array.Resize(
                ref portalMovementHits,
                portalMovementHits.Length * 2);
        }

        Vector3 remoteEnd = remoteStart + remoteDelta;
        bool found = false;
        float nearestDistance = float.PositiveInfinity;
        for (int hitIndex = 0; hitIndex < hitCount; ++hitIndex)
        {
            RaycastHit hit = portalMovementHits[hitIndex];
            Collider collider = hit.collider;
            if (collider == null ||
                IsPortalOwnedCollider(collider) ||
                collider.attachedRigidbody != null ||
                (movingRoot != null &&
                 collider.transform.IsChildOf(movingRoot)))
                continue;

            // CTrace_PlayerAABB_vs_Portals only honours a portal trace that
            // does NOT start inside geometry:
            //     if ( RealTrace.startsolid || ( !PortalTrace.startsolid && ... ) )
            // A remote hull that begins embedded in the exit wall is the
            // "near the portal, hitting remote geometry that overlaps our local
            // space in non-euclidean ways" case, and Source deliberately
            // discards it. That is exactly the floor-portal-to-wall-portal
            // case: the standing hull maps onto the exit plane, the extent
            // shift puts one side exactly on that plane, so the very first
            // tick of descent pushes the remote AABB into the wall that hosts
            // the exit portal. Keeping that hit reads as "collides with the
            // other portal's wall" and pins the player on the floor portal,
            // because a startsolid BoxCast reports distance 0 and the slide
            // solver can never advance.
            //
            // The remote hull only has to be tested while it is outside the
            // exit geometry; once it is inside, the player has not teleported
            // yet and the normal local trace is the authority.
            //
            // A BoxCast that starts overlapping reports distance 0, so this is
            // the exact startsolid test rather than a proximity tolerance: a
            // wider epsilon would also swallow genuine hits just outside the
            // exit wall.
            if (hit.distance <= RemoteStartSolidEpsilon)
                continue;

            if (IsPortalWallAtRemoteOpening(
                    hit, exit, remoteStart, remoteHalfExtents,
                    hullRotation, remoteEnd))
                continue;

            float distance = hit.distance *
                (localDistance / remoteDistance);
            if (distance >= nearestDistance)
                continue;

            // TEMPORARY REMOTE-TRACE DIAGNOSTIC. Names the object the player's
            // hull would hit after being mapped into the exit portal's space,
            // and how far the mapped hull started from the exit plane. This is
            // the only path that behaves differently for a floor-to-floor pair
            // and a floor-to-wall pair, so it has to be visible in the log.
            if (Time.unscaledTime - _lastRemoteTraceLogTime >= 0.5f)
            {
                _lastRemoteTraceLogTime = Time.unscaledTime;
                Vector3 exitNormal = GetPortalPlaneNormal(exit);
                Debug.Log("[PortalRemote] hit=" + collider.name +
                    " exit=" + exit.name +
                    " dist=" + distance.ToString("F4") +
                    " rawDist=" + hit.distance.ToString("F4") +
                    " startFromExitPlane=" +
                        Vector3.Dot(
                            remoteStart - exit.transform.position,
                            exitNormal).ToString("F4") +
                    " normal=" + hit.normal);
            }

            hit.distance = distance;
            hit.normal = Quaternion.Inverse(portalRotation) * hit.normal;
            hit.point = MapPortalPoint(
                exit,
                entry,
                hit.point - remoteShift);
            nearest = hit;
            nearestDistance = distance;
            // Source only treats the ramp as special when the accepted trace
            // actually hits and the hit normal points along movement up
            // (CTrace_PlayerAABB_vs_Portals::HitPortalRamp).
            contactedTransitionRamp = rampContact &&
                rampFraction <= planeFraction + 0.0001f &&
                Vector3.Dot(hit.normal, movementUp) > 0f;
            found = true;
        }
        return found;
    }

    private static bool TryGetTransitionRampContact(
        Portal portal,
        Vector3 remoteStart,
        Vector3 remoteDelta,
        Vector3 movingHalfExtents,
        out float contactFraction)
    {
        contactFraction = 0f;
        if (portal == null)
            return false;

        // CPortalSimulator builds pAABBAngleTransformCollideable from the
        // lower portal-hole carve. Its six planes form a box: 1024 HU wide,
        // from 0.65 HU below the opening to -1024 HU, and 1/32..64 HU behind
        // the portal plane. The box is transformed through the linked portal
        // before Source traces the remote player hull against it.
        const float innerCarveHu = SourceAabbCarveHu;
        const float farExtentHu = 1024f;
        const float backExtentHu = 64f;
        const float nearPlaneHu = 1f / 32f;
        float unitScale = 1f / PortalTransformMath.HammerUnitsPerUnityUnit;
        float bottom = -portal.GetPortalHalfSizeWorld().y -
            innerCarveHu * unitScale;
        float farBottom = -farExtentHu * unitScale;
        float back = backExtentHu * unitScale;
        float nearPlane = nearPlaneHu * unitScale;
        if (bottom <= farBottom)
            return false;

        Transform portalTransform = portal.transform;
        Vector3 rampCenter = portalTransform.position +
            portalTransform.up * ((bottom + farBottom) * 0.5f) +
            portalTransform.forward * ((back + nearPlane) * 0.5f);
        Vector3 rampHalfExtents = new Vector3(
            farExtentHu * unitScale,
            (bottom - farBottom) * 0.5f,
            (back - nearPlane) * 0.5f);
        return SweptAabbIntersectsOrientedBox(
            remoteStart,
            remoteDelta,
            movingHalfExtents,
            rampCenter,
            rampHalfExtents,
            portalTransform.rotation,
            out contactFraction);
    }

    private static bool SweptAabbIntersectsOrientedBox(
        Vector3 start,
        Vector3 delta,
        Vector3 movingHalfExtents,
        Vector3 boxCenter,
        Vector3 boxHalfExtents,
        Quaternion boxRotation,
        out float contactFraction)
    {
        contactFraction = 0f;
        float entry = 0f;
        float exit = 1f;
        Vector3 boxRight = boxRotation * Vector3.right;
        Vector3 boxUp = boxRotation * Vector3.up;
        Vector3 boxForward = boxRotation * Vector3.forward;

        if (!IntersectSweptBoxesOnAxis(
                Vector3.right, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.up, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.forward, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                boxRight, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                boxUp, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                boxForward, start, delta, movingHalfExtents,
                boxCenter, boxHalfExtents, boxRight, boxUp, boxForward,
                ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.right, boxRight), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.right, boxUp), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.right, boxForward), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.up, boxRight), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.up, boxUp), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.up, boxForward), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.forward, boxRight), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.forward, boxUp), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit) ||
            !IntersectSweptBoxesOnAxis(
                Vector3.Cross(Vector3.forward, boxForward), start, delta,
                movingHalfExtents, boxCenter, boxHalfExtents,
                boxRight, boxUp, boxForward, ref entry, ref exit))
            return false;

        if (exit < 0f || entry > 1f)
            return false;
        contactFraction = Mathf.Clamp01(entry);
        return true;
    }

    private static bool IntersectSweptBoxesOnAxis(
        Vector3 axis,
        Vector3 start,
        Vector3 delta,
        Vector3 movingHalfExtents,
        Vector3 boxCenter,
        Vector3 boxHalfExtents,
        Vector3 boxRight,
        Vector3 boxUp,
        Vector3 boxForward,
        ref float entry,
        ref float exit)
    {
        float axisLengthSquared = axis.sqrMagnitude;
        if (axisLengthSquared < 0.000001f)
            return true;
        axis /= Mathf.Sqrt(axisLengthSquared);

        float movingRadius =
            Mathf.Abs(axis.x) * movingHalfExtents.x +
            Mathf.Abs(axis.y) * movingHalfExtents.y +
            Mathf.Abs(axis.z) * movingHalfExtents.z;
        float boxRadius =
            Mathf.Abs(Vector3.Dot(axis, boxRight)) * boxHalfExtents.x +
            Mathf.Abs(Vector3.Dot(axis, boxUp)) * boxHalfExtents.y +
            Mathf.Abs(Vector3.Dot(axis, boxForward)) * boxHalfExtents.z;
        float radius = movingRadius + boxRadius;
        float origin = Vector3.Dot(start - boxCenter, axis);
        float travel = Vector3.Dot(delta, axis);

        if (Mathf.Abs(travel) < 0.000001f)
            return origin >= -radius && origin <= radius;

        float first = (-radius - origin) / travel;
        float second = (radius - origin) / travel;
        if (first > second)
        {
            float swap = first;
            first = second;
            second = swap;
        }

        entry = Mathf.Max(entry, first);
        exit = Mathf.Min(exit, second);
        return entry <= exit;
    }

    private static bool HasActivePair(Portal portal)
    {
        if (portal == null || !portal.isPlaced ||
            portal.otherPortal == null || !portal.otherPortal.isPlaced ||
            portal.otherPortal.otherPortal != portal ||
            portal.wallCollider == null ||
            portal.otherPortal.wallCollider == null ||
            portal.portalCollider == null ||
            portal.otherPortal.portalCollider == null)
            return false;

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        Vector3 otherHalfSize = portal.otherPortal.GetPortalHalfSizeWorld();
        return Mathf.Abs(halfSize.x - otherHalfSize.x) <=
                PlayerCutoutTolerance &&
            Mathf.Abs(halfSize.y - otherHalfSize.y) <=
                PlayerCutoutTolerance;
    }

    private static Quaternion GetPortalRotation(Portal entry, Portal exit)
    {
        return PortalTransformMath.GetEntryToExitRotation(entry, exit);
    }

    public static Vector3 GetPortalPlaneNormal(Portal portal)
    {
        // PortalPlacement orients the portal's local +Z axis into the wall.
        // Source portal planes use the outward-facing normal.
        return -portal.transform.forward;
    }

    /// <summary>
    /// CProp_Portal::GetMinimumExitSpeed (prop_portal_shared.cpp:201-265).
    /// Source keeps a player from walking straight back into a floor or
    /// upward-facing exit by guaranteeing a minimum speed along the exit
    /// portal's forward (outward) axis. Without it the player materialises
    /// with no outward velocity, falls onto the exit plane next command and
    /// re-enters, ping-ponging between the pair. This is a VELOCITY fix, not
    /// a landing-position push; the position stays the plain portal transform.
    /// </summary>
    private static float GetSourceMinimumExitSpeed(
        Portal exitPortal,
        Vector3 exitCenter,
        Vector3 playerHalfExtents,
        float gravityAcceleration)
    {
        Vector3 forward = GetPortalPlaneNormal(exitPortal);
        if (forward.sqrMagnitude < 0.000001f)
            return 0f;
        forward.Normalize();

        float floorMinimum =
            300f / PortalTransformMath.HammerUnitsPerUnityUnit;
        // Source uses Z as up; Unity uses Y. Portal-plane normal.y maps to
        // Source normal.z. cos(30deg) is the "on floor" threshold.
        const float cosPiOverSix = 0.8660254037844386f;
        bool exitOnFloor = forward.y > cosPiOverSix;
        if (exitOnFloor)
            return floorMinimum;

        // Only forward facing up by more than 30 degrees (m_vForward.z > 0.5)
        // gets the perch computation; plain wall exits get no minimum.
        if (forward.y <= 0.5f)
            return 0f;

        float gravity = gravityAcceleration > 0f
            ? gravityAcceleration
            : 800f / PortalTransformMath.HammerUnitsPerUnityUnit;

        // prop_portal_shared.cpp:232-258: solve the ballistic minimum speed
        // that lands the hull on the portal's bottom edge ("perch") instead
        // of letting the ground be pulled out from under it.
        Vector3 upward = exitPortal.transform.up;
        Vector3 perch = exitPortal.transform.position -
            upward * exitPortal.GetPortalHalfSizeWorld().y;
        Vector3 testBBoxPoint = exitCenter;
        testBBoxPoint.y -= playerHalfExtents.y;
        Vector3 testToPerch = perch - testBBoxPoint;
        Vector3 right = exitPortal.transform.right;
        testToPerch -= Vector3.Dot(testToPerch, right) * right;

        float horizontalDistance = Mathf.Sqrt(
            testToPerch.x * testToPerch.x +
            testToPerch.z * testToPerch.z);
        float horizontalForward = Mathf.Sqrt(
            forward.x * forward.x + forward.z * forward.z);
        // SolveQuadratic(a, 0, c) with:
        //   a = forward.y * -2 * (horizontalDistance * horizontalForward
        //                        - testToPerch.y * forward.y)
        //   c = horizontalDistance^2 * gravity
        float a = (forward.y * -2f) *
            ((horizontalDistance * horizontalForward) -
             (testToPerch.y * forward.y));
        float c = horizontalDistance * horizontalDistance * gravity;
        float disc = -4f * a * c;
        if (Mathf.Abs(a) < 0.000001f || disc < 0f)
            return 0f;
        float rootA = Mathf.Sqrt(disc) / (2f * a);
        float rootB = -rootA;
        float maxRoot = Mathf.Max(rootA, rootB);
        if (maxRoot <= 0f)
            return 0f;
        return Mathf.Min(maxRoot, floorMinimum);
    }

