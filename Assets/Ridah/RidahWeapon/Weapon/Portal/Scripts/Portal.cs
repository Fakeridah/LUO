    /// <summary>
    /// True when a wall collider is a linked portal's host wall and the hull
    /// only partially overlaps the aperture. Source's inverse-hole shape
    /// makes this the normal carved-edge contact, not a stuck overlap.
    /// </summary>
    public static bool IsPortalWallAtApertureEdge(
        Collider wallCollider,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation)
    {
        if (wallCollider == null)
            return false;

        Portal portal = null;
        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal candidate = ActivePortals[i];
            if (!HasActivePair(candidate) ||
                candidate.wallCollider == null ||
                (wallCollider != candidate.wallCollider &&
                 !wallCollider.transform.IsChildOf(
                     candidate.wallCollider.transform)))
                continue;
            portal = candidate;
            break;
        }
        if (portal == null)
            return false;

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        Vector3 hullRight = hullRotation * Vector3.right;
        Vector3 hullUp = hullRotation * Vector3.up;
        Vector3 hullForward = hullRotation * Vector3.forward;
        float halfWidth = ProjectHalfExtent(
            portal.transform.right, hullRight, hullUp, hullForward,
            hullHalfExtents);
        float halfHeight = ProjectHalfExtent(
            portal.transform.up, hullRight, hullUp, hullForward,
            hullHalfExtents);
        Vector3 offset = hullCenter - portal.transform.position;
        float rightOffset = Vector3.Dot(offset, portal.transform.right);
        float upOffset = Vector3.Dot(offset, portal.transform.up);

        float rightLimit = halfSize.x + PlayerCutoutTolerance;
        float upLimit = halfSize.y + PlayerCutoutTolerance;
        float downLimit = -halfSize.y - PlayerCutoutTolerance -
            SourcePortalBottomCarve;
        float rightOver = Mathf.Abs(rightOffset) + halfWidth - rightLimit;
        float upOver = upOffset + halfHeight - upLimit;
        float downOver = downLimit - (upOffset - halfHeight);
        return Mathf.Max(rightOver, Mathf.Max(upOver, downOver)) > 0f;
    }

    /// <summary>
    /// Mirrors CPortalGameMovement::HandlePortalling: detect the hull center
    /// crossing a linked portal during this movement command, then transform
    /// the already-moved center and velocity in the same command.
    /// </summary>
    public static bool TryHandlePlayerMovement(
        PortablePlayer player,
        Vector3 previousRootPosition,
        ref Vector3 currentRootPosition,
        Vector3 hullHalfExtents,
        Vector3 duckHullHalfExtents,
        Vector3 movementUp,
        ref Vector3 velocity,
        bool wasGrounded,
        float gravityAcceleration,
        float frameTime,
        out Quaternion portalRotation,
        out bool forceDuck,
        out Portal entryPortal,
        out Portal exitPortal,
        out Vector3 transformedOldEyePosition)
    {
        portalRotation = Quaternion.identity;
        forceDuck = false;
        entryPortal = null;
        exitPortal = null;
        transformedOldEyePosition = Vector3.zero;
        if (player == null || movementUp.sqrMagnitude < 0.5f)
            return false;

        movementUp.Normalize();
        Vector3 centerOffset = movementUp * hullHalfExtents.y;
        Vector3 previousCenter = previousRootPosition + centerOffset;
        Vector3 currentCenter = currentRootPosition + centerOffset;
        float nearestCrossing = float.PositiveInfinity;
        float crossingFraction = 0f;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal candidate = ActivePortals[i];
            if (!HasActivePair(candidate))
                continue;

            // PlacePortal intentionally stores transform.forward pointing
            // into the host wall (-hit.normal). The traversable/front side
            // is therefore the opposite direction.
            // The centre must reach the plane - that stays a centre test.
            // On a shallow slope the centre would have to sink a whole
            // half-height to do that, and the ground stops it first, so the
            // portal never fires. Pull the test plane only part-way toward
            // the player (a middle value, not all the way to the feet).
            // On a wall |up . normal| is zero, so nothing changes there.
            Vector3 normal = GetPortalPlaneNormal(candidate);
            float crossRelief = SourcePortalCrossReliefFraction *
                hullHalfExtents.y *
                Mathf.Abs(Vector3.Dot(movementUp, normal));

            // Do not immediately re-enter a FLOOR or SLOPE portal we just
            // came out of. The landing centre sits on that portal's plane,
            // and the relief above makes "on the plane" read as "behind the
            // test plane". If the hull is held for a command, the settled-
            // behind-plane fallback below accepts that stationary landing as
            // a fresh crossing and fires straight back - a two-portal ping-
            // pong. Source never sees this because it tests the exact centre
            // plane; emulate the same effect by ignoring this one portal
            // until the centre is clearly back on the traversable side.
            // No position is changed here.
            //
            // A WALL portal needs none of this: |up . normal| is zero, so the
            // relief is zero, the exact centre test already behaves like
            // Source, and exiting a wall never re-triggers. Skip it entirely.
            if (candidate == s_recentExitPortal && crossRelief > 0f)
            {
                float frontDistance = Vector3.Dot(
                    currentCenter - candidate.transform.position, normal);
                if (frontDistance <= crossRelief + SourceExitClearanceMargin)
                {
                    if (Time.unscaledTime - _lastCrossingLogTime >= 0.5f)
                    {
                        _lastCrossingLogTime = Time.unscaledTime;
                        Debug.Log("[PortalCross] HOLD recent exit " +
                            candidate.name + " front=" +
                            frontDistance.ToString("F3") + " relief=" +
                            crossRelief.ToString("F3"));
                    }
                    continue;
                }
                s_recentExitPortal = null;
            }

            float startDistance = Vector3.Dot(
                previousCenter - candidate.transform.position, normal) -
                crossRelief;
            float endDistance = Vector3.Dot(
                currentCenter - candidate.transform.position, normal) -
                crossRelief;
            float distanceTravelled = startDistance - endDistance;
            float normalExtent = ProjectHalfExtent(
                normal,
                Vector3.right,
                Vector3.up,
                Vector3.forward,
                hullHalfExtents);
            // A hull that already rests behind the plane has reached the
            // teleport point but is no longer moving toward it. Source's
            // CheckStuck consumes the whole command when it cannot free the
            // hull, so the command that crossed the plane can be dropped
            // entirely and the hull is then left sitting in the recess with
            // distanceTravelled == 0. The plain "did it move this command"
            // gate below would then discard that crossing on every following
            // command too, which on a floor reads as sinking into a shallow
            // pit and never teleporting - randomly, because whether the
            // crossing command got blocked depends on how the hull grazed the
            // recess walls on the way in. Accept the settled case instead:
            // behind the plane, still within the recess the carve allows, and
            // not currently backing out of it. The aperture test further down
            // is the real guard, and the recess back cap only lets "behind
            // the plane" be reached from the traversable side.
            bool settledBehindPlane =
                startDistance < 0f && distanceTravelled > -0.0001f;
            // The start-distance guard is measured against the REAL plane.
            // Both distances were shifted by crossRelief, so subtract it here
            // too or the "already deep inside" recovery window shrinks by the
            // relief amount and a shallow slope that settled in the opening
            // gets discarded forever.
            if (startDistance < -normalExtent - PlayerCutoutTolerance -
                    crossRelief ||
                endDistance >= -0.000001f ||
                (distanceTravelled <= 0.000001f && !settledBehindPlane))
                continue;

            // Normally the centre crosses this plane in the current move.
            // If a prior blocked move left the hull slightly inside the
            // wall, Source's portal-environment state still recognizes the
            // transition; recover that equivalent case while the hull
            // overlaps the plane and continues inward.
            bool recoveringFromWallOverlap = startDistance < 0f;
            if (settledBehindPlane && distanceTravelled <= 0.000001f)
                LogSettledCrossing(candidate, currentCenter, endDistance);
            float fraction = recoveringFromWallOverlap
                ? 0f
                : startDistance / distanceTravelled;
            if (fraction < 0f || fraction > 1f ||
                fraction >= nearestCrossing)
                continue;

            Vector3 centerAtPlane = recoveringFromWallOverlap
                ? currentCenter - normal * endDistance
                : Vector3.Lerp(previousCenter, currentCenter, fraction);
            // The host wall now carries a real carved hole, so the geometry
            // itself decides whether the hull can reach the plane: the centre
            // only gets past the front face from inside the opening. Demanding
            // a whole-hull fit here therefore adds no protection, it only
            // rejects crossings the hole already allowed - and on a floor
            // portal that reads as falling through without teleporting,
            // because a through-hole lets the hull sink past the plane at the
            // rim where a standing hull never fits. Overlap is the correct
            // test once the aperture is real.
            if (!IntersectsPortalOpening(candidate, centerAtPlane,
                hullHalfExtents, Quaternion.identity, PlayerCutoutTolerance,
                SourcePortalBottomCarve))
            {
                LogCrossingRejection(
                    candidate, centerAtPlane, hullHalfExtents,
                    startDistance, endDistance);
                continue;
            }

            Portal destination = candidate.otherPortal;
            Quaternion rotation = GetPortalRotation(candidate, destination);
            bool transitionNeedsDuck = ShouldForcePortalCrouch(
                candidate, movementUp, hullHalfExtents, duckHullHalfExtents);
            // No pre-simulation of the exit. Every gate that used to ask
            // "would the hull fit the destination opening?" - the whole-hull
            // fit, the aperture overlap and the clamp that tried to repair it
            // - is deliberately gone. They could only ever refuse a crossing
            // the entry hole had already allowed, and on a floor portal that
            // refusal reads as falling through without ever arriving. The
            // landing is the exit portal's own centre (see below), which is
            // inside the opening by construction, so there is nothing left to
            // validate and nothing that can straddle the rim.
            nearestCrossing = fraction;
            entryPortal = candidate;
            exitPortal = destination;
            portalRotation = rotation;
            forceDuck = transitionNeedsDuck;
            crossingFraction = fraction;
        }

        if (entryPortal == null || exitPortal == null)
            return false;

        // Land at the plain portal-transform position, matching
        // CPortalGameMovement::HandlePortalling for static portals. Source
        // transforms the hull centre and then removes the origin-to-centre
        // offset in the DESTINATION world (vTransformedMoveCenter -
        // vOriginToCenter); that offset is never rotated by the portal matrix.
        // Source pushes the exit centre outward along the normal only for
        // MOBILE portals, so every static portal (floor / wall / slope) keeps
        // the mapped depth as-is. MapPortalPoint is a rigid transform, so the
        // incoming in-plane position across the opening is preserved. No
        // support push, fit test, clamp or exit-side pre-simulation here.
        Vector3 transformedCenter = MapPortalPoint(
            entryPortal, exitPortal, currentCenter);
        Vector3 exitCenterOffset = forceDuck
            ? movementUp * duckHullHalfExtents.y
            : centerOffset;
        Vector3 transformedRoot = transformedCenter - exitCenterOffset;
        // The eye offset is a render-only correction: Source transforms the
        // pre-teleport eye position by the same portal matrix and nothing else.
        transformedOldEyePosition = MapPortalPoint(
            entryPortal, exitPortal, player.GetMovementEyePosition());
        currentRootPosition = transformedRoot;
        // HandlePortalling removes the part of this command's gravity that
        // belongs after the crossing, rotates the pre-exit velocity, then
        // reapplies gravity in the destination world.
        Vector3 postPortalGravityVelocity = wasGrounded
            ? Vector3.zero
            : -movementUp * gravityAcceleration * frameTime *
                (1f - crossingFraction);
        velocity -= postPortalGravityVelocity;
        velocity = portalRotation * velocity;
        velocity += postPortalGravityVelocity * 1.008f;

        // CPortalGameMovement "velocity hacks" (portal_gamemovement.cpp:2442):
        // guarantee a minimum outward speed at a floor / upward-slope exit so
        // the hull clears the exit plane instead of falling back through it
        // and re-entering the pair next command. Speed only - no position push.
        Vector3 exitForward = GetPortalPlaneNormal(exitPortal);
        if (exitForward.sqrMagnitude > 0.000001f)
        {
            exitForward.Normalize();
            float minimumExitSpeed = GetSourceMinimumExitSpeed(
                exitPortal, transformedCenter, hullHalfExtents,
                gravityAcceleration);
            float forwardSpeed = Vector3.Dot(velocity, exitForward);
            if (forwardSpeed < minimumExitSpeed)
                velocity += exitForward * (minimumExitSpeed - forwardSpeed);
        }
        if (Time.unscaledTime - _lastCrossingLogTime >= 0.5f)
        {
            _lastCrossingLogTime = Time.unscaledTime;
            Debug.Log("[PortalCross] MAPPED " + entryPortal.name + " -> " +
                exitPortal.name + " root=" + currentRootPosition.ToString("F2") +
                " vel=" + velocity.ToString("F2") +
                " rot=" + portalRotation.eulerAngles.ToString("F1") +
                " entryRot=" + entryPortal.transform.eulerAngles.ToString("F1") +
                " exitRot=" + exitPortal.transform.eulerAngles.ToString("F1"));
        }
        return true;
    }

    /// <summary>
    /// Commits player-only portal state after the movement controller has
    /// confirmed the mapped exit pose is clear.
    /// </summary>
    public static void CommitPlayerTeleport(
        PortablePlayer player,
        Portal exitPortal,
        Quaternion portalRotation)
    {
        if (player == null || exitPortal == null)
            return;

        // The exit portal owns the player until the centre has moved clearly
        // back onto its traversable side (see TryHandlePlayerMovement).
        s_recentExitPortal = exitPortal;
        player.ApplyPortalRotation(portalRotation);
    }

    /// <summary>
    /// Finds an active portal whose Source ghosting volume contains an
    /// object's bounds. Source searches a sphere around the portal, then tests
    /// the entity against the portal-hole volume and rejects entities too far
    /// behind the portal plane. This is polled so a Rigidbody is not required.
    /// </summary>
    public static Portal FindPortalableObjectOccupancy(Bounds objectBounds)
    {
        Portal nearest = null;
        float nearestDistance = float.PositiveInfinity;
        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal candidate = ActivePortals[i];
            if (candidate == null || !candidate.isPlaced ||
                !HasActivePair(candidate) ||
                candidate.portalCollider == null ||
                !candidate.portalCollider.enabled)
                continue;

            Vector3 offset = objectBounds.center - candidate.transform.position;
            float searchRadius = candidate.GetPortalHalfSizeWorld().y;
            if (offset.sqrMagnitude > searchRadius * searchRadius)
                continue;

            Vector3 normal = GetPortalPlaneNormal(candidate);
            float centerDistance = Vector3.Dot(offset, normal);
            float normalExtent = ProjectHalfExtent(
                normal,
                Vector3.right,
                Vector3.up,
                Vector3.forward,
                objectBounds.extents);
            if (centerDistance < -SourceGhostBackSideLimit ||
                centerDistance - normalExtent > -SourceGhostHoleFrontInset ||
                centerDistance + normalExtent < -SourceGhostHoleDepth ||
                !IsPortalableObjectInsideGhostHole(candidate, objectBounds))
                continue;

            float distance = offset.sqrMagnitude;
            if (distance >= nearestDistance)
                continue;

            nearest = candidate;
            nearestDistance = distance;
        }

        return nearest;
    }

    private static bool IsPortalableObjectInsideGhostHole(
        Portal portal,
        Bounds objectBounds)
    {
        Vector3 halfSize = portal.GetPortalHalfSizeWorld() * 0.98f;
        Vector3 offset = objectBounds.center - portal.transform.position;
        float halfWidth = ProjectHalfExtent(
            portal.transform.right,
            Vector3.right,
            Vector3.up,
            Vector3.forward,
            objectBounds.extents);
        float halfHeight = ProjectHalfExtent(
            portal.transform.up,
            Vector3.right,
            Vector3.up,
            Vector3.forward,
            objectBounds.extents);
        float horizontalOffset = Vector3.Dot(offset, portal.transform.right);
        float verticalOffset = Vector3.Dot(offset, portal.transform.up);

        // CPortalSimulator builds the ghosting collision volume from a portal
        // opening inset to 98% of its width and height. For regular props,
        // Source tests their collision AABB against that volume.
        return Mathf.Abs(horizontalOffset) <= halfSize.x + halfWidth &&
            Mathf.Abs(verticalOffset) <= halfSize.y + halfHeight;
    }

