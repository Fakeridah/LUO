    public static void LogPortalHostContact(
        RaycastHit hit,
        Vector3 hullCenter,
        bool ignored)
    {
        if (hit.collider == null)
            return;

        float now = Time.unscaledTime;
        if (now - _lastHostContactLogTime < 0.5f)
            return;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal portal = ActivePortals[i];
            if (portal == null || portal.wallCollider == null)
                continue;
            if (hit.collider != portal.wallCollider &&
                !hit.collider.transform.IsChildOf(
                    portal.wallCollider.transform))
                continue;

            _lastHostContactLogTime = now;
            Vector3 planeNormal = GetPortalPlaneNormal(portal);
            Vector3 contact = hit.point - portal.transform.position;
            Vector3 center = hullCenter - portal.transform.position;
            Debug.Log("[PortalBlock] " + (ignored ? "IGNORED" : "KEPT") +
                " portal=" + portal.name +
                " collider=" + hit.collider.name +
                " carved=" + IsCarvedWall(portal) +
                " dist=" + hit.distance.ToString("F4") +
                " hit(r,u,n)=(" +
                    Vector3.Dot(contact, portal.transform.right).ToString("F3") +
                    "," +
                    Vector3.Dot(contact, portal.transform.up).ToString("F3") +
                    "," +
                    Vector3.Dot(contact, planeNormal).ToString("F3") + ")" +
                " center(r,u,n)=(" +
                    Vector3.Dot(center, portal.transform.right).ToString("F3") +
                    "," +
                    Vector3.Dot(center, portal.transform.up).ToString("F3") +
                    "," +
                    Vector3.Dot(center, planeNormal).ToString("F3") + ")" +
                " portalHalf=" + portal.GetPortalHalfSizeWorld());
            return;
        }
    }

