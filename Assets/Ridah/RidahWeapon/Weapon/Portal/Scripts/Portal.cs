    private static bool FitsPortalOpening(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        float bottomMargin = 0f)
    {
        if (portal == null || portal.portalCollider == null)
            return false;

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        Vector3 hullRight = hullRotation * Vector3.right;
        Vector3 hullUp = hullRotation * Vector3.up;
        Vector3 hullForward = hullRotation * Vector3.forward;
        float halfWidth = ProjectHalfExtent(
            portal.transform.right,
            hullRight,
            hullUp,
            hullForward,
            hullHalfExtents);
        float halfHeight = ProjectHalfExtent(
            portal.transform.up,
            hullRight,
            hullUp,
            hullForward,
            hullHalfExtents);
        Vector3 offset = hullCenter - portal.transform.position;
        float upOffset = Vector3.Dot(offset, portal.transform.up);

        // Whole-hull test, matching the inverse-hole shape: the hull must fit
        // completely inside the opening in both axes. Source's transition
        // ramp carves only BELOW the lower edge, so bottomMargin widens the
        // lower side only; the upper side must not be expanded by halfHeight.
        return Mathf.Abs(Vector3.Dot(offset, portal.transform.right)) +
                halfWidth <= halfSize.x + PlayerCutoutTolerance &&
            upOffset + halfHeight <=
                halfSize.y + PlayerCutoutTolerance &&
            upOffset - halfHeight >=
                -halfSize.y - PlayerCutoutTolerance - bottomMargin;
    }

    /// <summary>
    /// Slide a mapped exit centre back inside the destination opening by the
    /// smallest offset that lets the whole hull fit. A hull that starts the
    /// destination sweep already overlapping reports zero distance, which the
    /// slide solver turns into a permanent stop, so both the crossing gate and
    /// the final landing clamp use this.
    /// </summary>
    /// <remarks>
    /// <paramref name="tolerance"/> defaults to the crossing allowance. The
    /// landing clamp passes zero: at the landing the hull can already be a
    /// little behind the exit plane, and any positive tolerance would then
    /// leave it straddling the rim, which is exactly the solid corner that
    /// freezes the player.
    /// </remarks>
    private static Vector3 ClampCenterIntoOpening(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        float bottomMargin,
        float tolerance = PlayerCutoutTolerance)
    {
        if (portal == null || portal.portalCollider == null)
            return hullCenter;

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        Vector3 right = portal.transform.right;
        Vector3 up = portal.transform.up;
        float halfWidth = ProjectHalfExtent(right, Vector3.right, Vector3.up,
            Vector3.forward, hullHalfExtents);
        float halfHeight = ProjectHalfExtent(up, Vector3.right, Vector3.up,
            Vector3.forward, hullHalfExtents);
        float maxRight = Mathf.Max(
            0f, halfSize.x + tolerance - halfWidth - ClampVerifyInset);
        float maxUp = Mathf.Max(
            0f, halfSize.y + tolerance - halfHeight - ClampVerifyInset);
        float minUp = -Mathf.Max(
            0f, halfSize.y + tolerance + bottomMargin -
                halfHeight - ClampVerifyInset);
        if (minUp > maxUp)
            minUp = maxUp;

        Vector3 offset = hullCenter - portal.transform.position;
        float rightOffset = Vector3.Dot(offset, right);
        float upOffset = Vector3.Dot(offset, up);
        float clampedRight = Mathf.Clamp(rightOffset, -maxRight, maxRight);
        float clampedUp = Mathf.Clamp(upOffset, minUp, maxUp);
        return hullCenter +
            right * (clampedRight - rightOffset) +
            up * (clampedUp - upOffset);
    }

    /// <summary>
    /// Slide a hull centre into a portal's aperture with the same geometry and
    /// zero tolerance as the landing clamp. Returns false when the centre
    /// already fits, so the caller can tell "repaired" from "nothing to do".
    /// </summary>
    /// <remarks>
    /// The post-teleport rescue needs this because the physics stuck test
    /// deliberately ignores portal hosts: a hull resting on the aperture rim
    /// is normal, and classifying it as stuck would zero the velocity every
    /// command. That same exclusion makes a landing that straddles the rim
    /// invisible, so it has to be detected geometrically instead.
    /// </remarks>
    public static bool TryFitHullIntoPortalOpening(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        out Vector3 fittedCenter)
    {
        fittedCenter = hullCenter;
        if (portal == null || portal.portalCollider == null)
            return false;

        Vector3 clamped = ClampCenterIntoOpening(
            portal, hullCenter, hullHalfExtents, SourcePortalBottomCarve, 0f);
        if ((clamped - hullCenter).sqrMagnitude < 0.000001f)
            return false;

        fittedCenter = clamped;
        return true;
    }

    /// <summary>
    /// Free a hull that is embedded in a carved portal host by sliding it into
    /// that host's aperture. Used by the periodic stuck recovery, which has no
    /// exit portal to work from and cannot see portal hosts through the normal
    /// physics test.
    /// </summary>
    /// <param name="hullCollider">
    /// The hull's own collider, posed at <paramref name="hullBasePosition"/>.
    /// </param>
    public static bool TryFitHullOutOfCarvedPortalHost(
        Collider hullCollider,
        Vector3 hullBasePosition,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        out Vector3 fittedCenter)
    {
        fittedCenter = hullCenter;
        if (hullCollider == null)
            return false;

        // Fit against the host the hull is buried deepest in. Two portals can
        // share a host, and picking the shallower one would leave the real
        // penetration untouched.
        Portal deepestPortal = null;
        float deepest = 0.0001f;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal portal = ActivePortals[i];
            if (!IsCarvedWall(portal))
                continue;

            Collider host = portal.wallCollider;
            if (host == null || host == hullCollider)
                continue;

            if (!Physics.ComputePenetration(
                    hullCollider,
                    hullBasePosition,
                    Quaternion.identity,
                    host,
                    host.transform.position,
                    host.transform.rotation,
                    out _,
                    out float depth) ||
                depth <= deepest)
                continue;

            deepest = depth;
            deepestPortal = portal;
        }

        if (deepestPortal == null)
            return false;

        Vector3 clamped = ClampCenterIntoOpening(
            deepestPortal, hullCenter, hullHalfExtents,
            SourcePortalBottomCarve, 0f);
        if ((clamped - hullCenter).sqrMagnitude < 0.000001f)
            return false;

        fittedCenter = clamped;
        return true;
    }

    private static bool IntersectsPortalOpening(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        float margin,
        float bottomMargin = 0f)
    {
        if (portal == null || portal.portalCollider == null)
            return false;

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        Vector3 hullRight = hullRotation * Vector3.right;
        Vector3 hullUp = hullRotation * Vector3.up;
        Vector3 hullForward = hullRotation * Vector3.forward;
        float halfWidth = ProjectHalfExtent(
            portal.transform.right,
            hullRight,
            hullUp,
            hullForward,
            hullHalfExtents);
        float halfHeight = ProjectHalfExtent(
            portal.transform.up,
            hullRight,
            hullUp,
            hullForward,
            hullHalfExtents);
        Vector3 offset = hullCenter - portal.transform.position;
        float upOffset = Vector3.Dot(offset, portal.transform.up);
        float upLimit = halfSize.y + halfHeight + margin;
        return Mathf.Abs(Vector3.Dot(offset, portal.transform.right)) <=
                halfSize.x + halfWidth + margin &&
            upOffset <= upLimit &&
            upOffset >= -upLimit - bottomMargin;
    }

    private static bool IsPortalWallAtRemoteOpening(
        RaycastHit hit,
        Portal exit,
        Vector3 remoteStart,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        Vector3 remoteEnd)
    {
        Collider candidate = hit.collider;
        if (candidate == null || exit == null || exit.wallCollider == null ||
            (candidate != exit.wallCollider &&
             !candidate.transform.IsChildOf(exit.wallCollider.transform)))
            return false;

        return FitsPortalWallPassage(
                exit,
                remoteStart,
                hullHalfExtents,
                hullRotation,
                remoteEnd - remoteStart,
                false,
                true);
    }

    private static bool IsPortalQuadSweepOverOpening(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullSweepDelta)
    {
        if (portal == null)
            return false;

        Vector3 normal = GetPortalPlaneNormal(portal);
        float startDistance = Vector3.Dot(
            hullCenter - portal.transform.position, normal);
        float sweepDistance = Vector3.Dot(hullSweepDelta, normal);
        float endDistance = startDistance + sweepDistance;
        float fraction;
        if (Mathf.Abs(sweepDistance) > 0.000001f &&
            startDistance * endDistance <= 0f)
            fraction = Mathf.Clamp01(-startDistance / sweepDistance);
        else
            fraction = Mathf.Abs(endDistance) < Mathf.Abs(startDistance)
                ? 1f
                : 0f;

        Vector3 centerAtPlane = hullCenter + hullSweepDelta * fraction;
        Vector3 offset = centerAtPlane - portal.transform.position;
        offset -= normal * Vector3.Dot(offset, normal);
        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        float margin = SourcePortalQuadMargin;
        return Mathf.Abs(Vector3.Dot(offset, portal.transform.right)) <=
                   halfSize.x + margin &&
               Vector3.Dot(offset, portal.transform.up) <=
                   halfSize.y + margin &&
               Vector3.Dot(offset, portal.transform.up) >=
                   -halfSize.y - margin - SourcePortalBottomCarve;
    }

    private static bool FitsPortalWallPassage(
        Portal portal,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        Vector3 hullSweepDelta,
        bool allowApertureEdgeOverlap,
        bool requireWholeHull = false)
    {
        Vector3 planeNormal = GetPortalPlaneNormal(portal);
        float startDistance = Vector3.Dot(
            hullCenter - portal.transform.position, planeNormal);
        float sweepDistance = Vector3.Dot(hullSweepDelta, planeNormal);
        float endDistance = startDistance + sweepDistance;

        float fraction;
        if (Mathf.Abs(sweepDistance) > 0.000001f &&
            startDistance * endDistance <= 0f)
        {
            fraction = Mathf.Clamp01(-startDistance / sweepDistance);
        }
        else
        {
            // A BoxCast reaches the wall when the hull edge touches it, often
            // before the hull center reaches the portal plane. Test the point
            // in this sweep closest to the plane so that an angled approach
            // does not acquire a one-frame wall lip.
            fraction = Mathf.Abs(endDistance) < Mathf.Abs(startDistance)
                ? 1f
                : 0f;
        }

        Vector3 centerAtPlane = hullCenter + hullSweepDelta * fraction;
        float distanceAtPlane = Vector3.Dot(
            centerAtPlane - portal.transform.position, planeNormal);
        centerAtPlane -= planeNormal * distanceAtPlane;

        float hullNormalExtent = ProjectHalfExtent(
            planeNormal,
            hullRotation * Vector3.right,
            hullRotation * Vector3.up,
            hullRotation * Vector3.forward,
            hullHalfExtents);
        if (Mathf.Abs(distanceAtPlane) >
            PlayerCutoutDepth + hullNormalExtent + PlayerCutoutTolerance)
            return false;

        if (requireWholeHull)
            return FitsPortalOpening(
                portal, centerAtPlane, hullHalfExtents, hullRotation,
                SourcePortalBottomCarve);

        return IntersectsPortalOpening(
            portal,
            centerAtPlane,
            hullHalfExtents,
            hullRotation,
            allowApertureEdgeOverlap
                ? PlayerCutoutMargin
                : PlayerCutoutTolerance,
            SourcePortalBottomCarve);
    }

    public static bool IsPortalOwnedCollider(Collider candidate)
    {
        return candidate != null &&
            candidate.GetComponentInParent<Portal>() != null;
    }

    /// <summary>
    /// The generated local collision patch around a portal: the aperture
    /// sleeve inside the host wall volume. It is real solid geometry for both
    /// movement and stuck recovery, so it must never be filtered through the
    /// aperture and must never be silently skipped when the hull is inside it.
    /// </summary>
    private static bool IsPortalPatchCollider(Collider candidate)
    {
        return candidate != null && PortalPatchColliders.Contains(candidate);
    }

    private static float ProjectHalfExtent(
        Vector3 axis,
        Vector3 hullRight,
        Vector3 hullUp,
        Vector3 hullForward,
        Vector3 hullHalfExtents)
    {
        return Mathf.Abs(Vector3.Dot(axis, hullRight)) * hullHalfExtents.x +
            Mathf.Abs(Vector3.Dot(axis, hullUp)) * hullHalfExtents.y +
            Mathf.Abs(Vector3.Dot(axis, hullForward)) * hullHalfExtents.z;
    }

    private static float Sign(float value)
    {
        return value > 0f ? 1f : value < 0f ? -1f : 0f;
    }

    private Vector3 GetPortalHalfSize()
    {
        BoxCollider box = portalCollider as BoxCollider;
        if (box != null)
            return box.size * 0.5f;

        Bounds bounds = portalCollider != null
            ? portalCollider.bounds
            : new Bounds(transform.position, new Vector3(2f, 4f, 0.6f));
        return new Vector3(
            Vector3.Dot(Abs(transform.right), bounds.extents),
            Vector3.Dot(Abs(transform.up), bounds.extents),
            Vector3.Dot(Abs(transform.forward), bounds.extents));
    }

    private Vector3 GetPortalHalfSizeWorld()
    {
        BoxCollider box = portalCollider as BoxCollider;
        if (box != null)
        {
            Vector3 localHalf = box.size * 0.5f;
            Vector3 scale = Abs(transform.lossyScale);
            return Vector3.Scale(localHalf, scale);
        }

        Bounds bounds = portalCollider != null
            ? portalCollider.bounds
            : new Bounds(transform.position, new Vector3(2f, 4f, 0.6f));
        return new Vector3(
            Vector3.Dot(Abs(transform.right), bounds.extents),
            Vector3.Dot(Abs(transform.up), bounds.extents),
            Vector3.Dot(Abs(transform.forward), bounds.extents));
    }

    private void UpdateAttachmentPose()
    {
        if (attachmentTransform == null)
            return;

        transform.SetPositionAndRotation(
            attachmentTransform.TransformPoint(attachmentLocalPosition),
            attachmentTransform.rotation * attachmentLocalRotation);
    }

    private static Vector3 Abs(Vector3 value)
    {
        return new Vector3(Mathf.Abs(value.x), Mathf.Abs(value.y),
            Mathf.Abs(value.z));
    }
