    public static bool ShouldIgnoreMovementCollision(
        RaycastHit hit,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        Vector3 hullSweepDelta,
        Vector3 duckHullHalfExtents,
        Vector3 movementUp)
    {
        Collider candidate = hit.collider;
        if (candidate == null)
            return false;
        if (IsPortalOwnedCollider(candidate))
            return true;
        if (IsPortalPatchCollider(candidate))
            return false;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal portal = ActivePortals[i];
            if (!HasActivePair(portal) ||
                (candidate != portal.wallCollider &&
                 !candidate.transform.IsChildOf(portal.wallCollider.transform)))
                continue;

            if (IsCarvedWall(portal))
            {
                WallCarveState state;
                if (CarvedWalls.TryGetValue(candidate.gameObject, out state))
                {
                    Portal capOwner = FindBackCapOwner(hit.triangleIndex, state);
                    if (capOwner != null)
                    {
                        // PlaneNormal points to the traversable face. A hull
                        // starting on that side can only be touching the cap
                        // during a front-to-back crossing, so the cap must be
                        // ignored. From behind the cap is the recess floor and
                        // it stays solid, full stop.
                        //
                        // This used to ignore the cap whenever the hull swept
                        // further in (sweepDistance < 0). A hull sitting in the
                        // recess is behind the plane and sweeping in, so that
                        // rule opened the floor under it: whenever the crossing
                        // was rejected on the same frame, the hull sank through
                        // the cap and out of the map. The cap sits past the
                        // crossing point, so nothing ever needs to pass it.
                        Vector3 planeNormal = GetPortalPlaneNormal(capOwner);
                        float startDistance = Vector3.Dot(
                            hullCenter - capOwner.transform.position,
                            planeNormal);
                        return startDistance > 0f;
                    }
                }
                continue;
            }

            // Thin / zero-thickness walls are not carved. Their own collision
            // must stay solid from the reverse side; only a hull approaching
            // from the traversable face may be filtered through the aperture.
            Vector3 apertureNormal = GetPortalPlaneNormal(portal);
            float apertureStart = Vector3.Dot(
                hullCenter - portal.transform.position, apertureNormal);
            float apertureSweep = Vector3.Dot(
                hullSweepDelta, apertureNormal);
            // Only a reverse-side hull actively sweeping toward the wall is
            // solid. A centre exactly on the portal plane with zero sweep is
            // a portal overlap, not wall penetration; treating equality as
            // reverse-side makes thin walls freeze in stuck recovery.
            if (apertureStart < 0f && apertureSweep > 0f)
                continue;

            // Movement filtering must use the SAME whole-hull aperture test
            // as TryHandlePlayerMovement. A centre-only quad check lets the
            // hull slip through the uncarved wall outside the visible portal
            // and then miss teleport because the teleport path still requires
            // the whole hull to fit. Stuck recovery keeps the centre-based
            // quad test below so the zero-sweep plane overlap does not freeze.
            Vector3 apertureHalfExtents = hullHalfExtents;
            if (duckHullHalfExtents.sqrMagnitude > 0.000001f &&
                ShouldForcePortalCrouch(
                    portal, movementUp, hullHalfExtents, duckHullHalfExtents))
                apertureHalfExtents = duckHullHalfExtents;

            if (FitsPortalWallPassage(
                    portal,
                    hullCenter,
                    apertureHalfExtents,
                    hullRotation,
                    hullSweepDelta,
                    false,
                    true))
                return true;
        }

        return false;
    }

