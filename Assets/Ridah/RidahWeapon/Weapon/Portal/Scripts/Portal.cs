    public Color GetOverlapMaterialColor(Color fallback)
    {
        if (IsVisibleAccentColor(portalColour))
            return portalColour;

        if (outlineRenderer != null &&
            TryGetMaterialAccentColor(
                outlineRenderer.sharedMaterial,
                "_OutlineColour",
                out Color outlineColor))
            return outlineColor;

        if (Renderer != null && Renderer.sharedMaterial != null)
        {
            Material surfaceMaterial = Renderer.sharedMaterial;
            if (TryGetMaterialAccentColor(
                    surfaceMaterial, "_BaseColor", out Color baseColor) ||
                TryGetMaterialAccentColor(
                    surfaceMaterial, "_Color", out baseColor) ||
                TryGetMaterialAccentColor(
                    surfaceMaterial, "_Colour", out baseColor))
                return baseColor;
        }

        return fallback;
    }

    private static bool TryGetMaterialAccentColor(
        Material material,
        string propertyName,
        out Color color)
    {
        color = Color.clear;
        if (material == null || !material.HasProperty(propertyName))
            return false;

        color = material.GetColor(propertyName);
        return IsVisibleAccentColor(color);
    }

    private static bool IsVisibleAccentColor(Color color)
    {
        float maximum = Mathf.Max(color.r, Mathf.Max(color.g, color.b));
        float minimum = Mathf.Min(color.r, Mathf.Min(color.g, color.b));
        return color.a > 0.01f && maximum > 0.05f &&
            maximum - minimum > 0.05f;
    }

    public void SetMaskID(int id)
    {
        if (Renderer != null)
            Renderer.material.SetInt("_MaskID", id);
    }

    private void OnTriggerEnter(Collider other)
    {
        if (otherPortal == null || !otherPortal.isPlaced)
            return;

        RegisterPortalableItem(other);

        PortalableObject portalObject =
            other.GetComponentInParent<PortalableObject>();
        if (portalObject != null)
            portalObject.RefreshPortalState();

        PortablePlayer player = other.GetComponentInParent<PortablePlayer>();
        if (player != null)
        {
            playerTriggerColliders.Add(other);
            if (HasActivePair(this))
                player.SetPortalEnvironment(this);
            placeEabled = false;
            return;
        }

        RefreshPlacementEnabled();
    }

    private void OnTriggerStay(Collider other)
    {
        // Source's CPortal_Player::m_hPortalEnvironment is updated while the
        // player is touching a portal, before the next movement command runs.
        // The old code only updated it after movement, so the portal-aware
        // trace always worked with stale state.
        RegisterPortalableItem(other);
        PortablePlayer player = other.GetComponentInParent<PortablePlayer>();
        if (player != null && HasActivePair(this))
            player.SetPortalEnvironment(this);
        PortalableObject portalObject =
            other.GetComponentInParent<PortalableObject>();
        if (portalObject != null)
            portalObject.RefreshPortalState();
    }

    private void RegisterPortalableItem(Collider candidate)
    {
        if (!HasActivePair(this) || candidate == null)
            return;

        int itemLayer = LayerMask.NameToLayer("Item");
        if (itemLayer >= 0)
            PortalableObject.EnsureForItemLayer(candidate, itemLayer);
    }

    private void RegisterPortalableItemsAtAperture()
    {
        if (!HasActivePair(this) || portalCollider == null ||
            !portalCollider.enabled)
            return;

        int itemLayer = LayerMask.NameToLayer("Item");
        if (itemLayer < 0)
            return;

        // Register scene props before they reach a portal. If the component
        // is first added after a fast object has already entered the carved
        // recess, its initial pose cannot describe the missed crossing.
        if (!itemLayerSceneScanComplete)
        {
            Collider[] sceneColliders =
                FindObjectsByType<Collider>(FindObjectsSortMode.None);
            for (int i = 0; i < sceneColliders.Length; ++i)
            {
                if (sceneColliders[i] != null)
                    PortalableObject.EnsureForItemLayer(
                        sceneColliders[i], itemLayer);
            }
            itemLayerSceneScanComplete = true;
        }

        // Item props are often moved by scripts without a Rigidbody. Sync
        // transforms before querying the small portal trigger volume so
        // registration does not depend on trigger callbacks.
        if (!Physics.autoSyncTransforms &&
            lastItemRegistrationSyncFrame != Time.frameCount)
        {
            Physics.SyncTransforms();
            lastItemRegistrationSyncFrame = Time.frameCount;
        }

        Bounds portalBounds = portalCollider.bounds;
        int count;
        while (true)
        {
            count = Physics.OverlapBoxNonAlloc(
                portalBounds.center,
                portalBounds.extents,
                portalItemRegistrationHits,
                Quaternion.identity,
                Physics.DefaultRaycastLayers,
                QueryTriggerInteraction.Ignore);
            if (count < portalItemRegistrationHits.Length)
                break;

            System.Array.Resize(
                ref portalItemRegistrationHits,
                portalItemRegistrationHits.Length * 2);
        }

        for (int i = 0; i < count; ++i)
        {
            Collider candidate = portalItemRegistrationHits[i];
            if (candidate != null)
                PortalableObject.EnsureForItemLayer(candidate, itemLayer);
        }
    }

    private void OnTriggerExit(Collider other)
    {
        PortalableObject portalObject =
            other.GetComponentInParent<PortalableObject>();
        if (portalObject != null)
            portalObject.RefreshPortalState();

        playerTriggerColliders.Remove(other);
        RefreshPlacementEnabled();
    }

    private void RefreshPlacementEnabled()
    {
        for (int i = portalObjects.Count - 1; i >= 0; --i)
        {
            if (portalObjects[i] == null)
                portalObjects.RemoveAt(i);
        }

        // A prop standing in the portal opening must not lock that portal's
        // gun slot. The portal simulator can transfer its occupancy when the
        // portal moves; only moving the portal while the player is inside the
        // trigger is unsafe for the player's active movement environment.
        placeEabled = playerTriggerColliders.Count == 0;
    }

    internal void SetPortalableObjectOccupancy(
        PortalableObject portalObject,
        bool occupied)
    {
        if (portalObject == null)
            return;

        if (occupied)
        {
            if (!portalObjects.Contains(portalObject))
                portalObjects.Add(portalObject);
        }
        else
        {
            portalObjects.Remove(portalObject);
        }

        RefreshPlacementEnabled();
    }

    public bool PlacePortal(Collider hitWall, Vector3 position,
        Quaternion rotation)
    {
        if (hitWall == null)
            return false;

        Transform previousParent = transform.parent;
        Vector3 previousPosition = transform.position;
        Quaternion previousRotation = transform.rotation;
        Vector3 previousLocalScale = transform.localScale;
        Collider previousWall = wallCollider;
        Transform previousAttachmentTransform = attachmentTransform;
        Vector3 previousAttachmentLocalPosition = attachmentLocalPosition;
        Quaternion previousAttachmentLocalRotation = attachmentLocalRotation;
        bool previousPlaced = isPlaced;
        bool previousActive = gameObject.activeSelf;
        bool previousPlaceEnabled = placeEabled;

        // Keep the portal geometry at its authored scale. Parenting it to a
        // scaled floor/wall makes a rotated child inherit non-uniform scale.
        transform.SetParent(null, true);
        transform.localScale = initialWorldScale;
        attachmentTransform = null;
        wallCollider = hitWall;
        // Lift the portal surface a hair off the host wall so the portal quad
        // and the wall are not coplanar. Without this the two surfaces
        // z-fight and the portal view flickers against the wall it is stuck
        // to. This matches the upstream placement (forward * 0.001) and is a
        // rendering-only nudge: the crossing plane / hull clearance logic
        // below is untouched.
        transform.position = position - rotation * Vector3.forward * 0.001f;
        transform.rotation = rotation;
        ApplySourcePortalSize();

        if (testTransform == null)
            testTransform = transform;

        Vector3 sourceOriginalPosition = position;

        // Placement is a single user action, so a rejection is worth one line:
        // "the click did nothing" is otherwise impossible to tell apart from
        // "the ray never hit anything".
        bool overhangsOk = FixOverhangs();
        bool intersectsOk = overhangsOk && FixIntersects();
        if (!overhangsOk || !intersectsOk)
        {
            Debug.Log("[PortalPlace] rejected: " +
                (overhangsOk ? "FixIntersects" : "no surface under the " +
                    "whole rectangle") +
                " host=" + hitWall.name +
                " at=" + position.ToString("F2"));
            wallCollider = previousWall;
            transform.SetParent(previousParent, true);
            transform.SetPositionAndRotation(previousPosition, previousRotation);
            transform.localScale = previousLocalScale;
            attachmentTransform = previousAttachmentTransform;
            attachmentLocalPosition = previousAttachmentLocalPosition;
            attachmentLocalRotation = previousAttachmentLocalRotation;
            isPlaced = previousPlaced;
            placeEabled = previousPlaceEnabled;
            if (!previousPlaced)
                gameObject.SetActive(false);
            else if (!gameObject.activeSelf)
                gameObject.SetActive(previousActive);
            return false;
        }

        ApplySourceFloorSnap();

        // VerifyPortalPlacement rejects a portal whose FitPortalOnSurface
        // adjustment moved farther than half the diagonal of a full-size
        // portal from the original shot position.
        Vector3 worldHalfSize = GetPortalHalfSizeWorld();
        float maxBumpSquared =
            (Mathf.Pow(2f * worldHalfSize.x, 2f) +
             Mathf.Pow(2f * worldHalfSize.y, 2f)) * 0.5f;
        if ((testTransform.position - sourceOriginalPosition).sqrMagnitude >
            maxBumpSquared)
        {
            Debug.Log("[PortalPlace] rejected: slid " +
                (testTransform.position - sourceOriginalPosition).magnitude
                    .ToString("F2") + " UU from the shot, limit " +
                Mathf.Sqrt(maxBumpSquared).ToString("F2"));
            wallCollider = previousWall;
            transform.SetParent(previousParent, true);
            transform.SetPositionAndRotation(previousPosition, previousRotation);
            transform.localScale = previousLocalScale;
            attachmentTransform = previousAttachmentTransform;
            attachmentLocalPosition = previousAttachmentLocalPosition;
            attachmentLocalRotation = previousAttachmentLocalRotation;
            isPlaced = previousPlaced;
            placeEabled = previousPlaceEnabled;
            if (!previousPlaced)
                gameObject.SetActive(false);
            else if (!gameObject.activeSelf)
                gameObject.SetActive(previousActive);
            return false;
        }

        if ((!CheckOverlap(false) || !CheckBackClearance(false)) &&
            !TrySlideOutOfOverlap())
        {
            // Re-run with logging so the rejection names the exact blocker;
            // the search above ran silently to avoid a line per candidate.
            CheckOverlap();
            CheckBackClearance();
            Debug.Log("[PortalPlace] rejected: overlap or back clearance at " +
                testTransform.position.ToString("F2") +
                " rot=" + testTransform.eulerAngles.ToString("F1"));
            wallCollider = previousWall;
            transform.SetParent(previousParent, true);
            transform.SetPositionAndRotation(previousPosition, previousRotation);
            transform.localScale = previousLocalScale;
            attachmentTransform = previousAttachmentTransform;
            attachmentLocalPosition = previousAttachmentLocalPosition;
            attachmentLocalRotation = previousAttachmentLocalRotation;
            isPlaced = previousPlaced;
            placeEabled = previousPlaceEnabled;
            if (!previousPlaced)
                gameObject.SetActive(false);
            else if (!gameObject.activeSelf)
                gameObject.SetActive(previousActive);
            return false;
        }

        if (previousPlaced)
            ClearPortalOccupants();

        transform.position = testTransform.position;
        transform.rotation = testTransform.rotation;

        // Source rebuilds the carved wall collision from the verified portal
        // pose, after FitPortalOnSurface/floor snap have finished. Rebuilding
        // before this point would cut the hole at the portal's old transform.
        // Resolve the original host collider BEFORE releasing the old carve.
        // A re-placement raycast can hit the generated MeshCollider; releasing
        // the old carve destroys that collider, so carving from `hitWall`
        // afterwards would rebuild from a destroyed reference and leave the
        // wall completely solid.
        Collider hostCollider = ResolveCarveHostCollider(hitWall);
        ReleaseWallCarve(this, previousWall);
        // A portal only opens a hole when the pair is complete. Before that
        // the host keeps its authored collider, so a lone portal is a visual
        // surface on a solid wall: it cannot be walked through and a floor
        // portal is not a bottomless pit.
        wallCollider = hostCollider;
        attachmentTransform = hitWall.transform;
        attachmentLocalPosition = attachmentTransform.InverseTransformPoint(
            transform.position);
        attachmentLocalRotation = Quaternion.Inverse(
            attachmentTransform.rotation) * transform.rotation;
        gameObject.SetActive(true);
        isPlaced = true;
        placeEabled = true;
        SyncPairCarve();
        return true;
    }

    /// <summary>
    /// A wall is only opened while both ends of the pair are placed and
    /// active. This is what keeps a lone portal a decorative surface on a
    /// solid wall - no pass-through and no bottomless floor hole - and opens
    /// both holes on the frame the second portal is placed.
    /// </summary>
    private void SyncPairCarve()
    {
        Portal partner = otherPortal;
        bool paired = isActiveAndEnabled && isPlaced &&
            partner != null && partner.isActiveAndEnabled &&
            partner.isPlaced && partner.otherPortal == this;
        UpdatePortalCarve(this, paired);
        if (partner != null)
            UpdatePortalCarve(partner, paired);
    }

    private static void UpdatePortalCarve(Portal portal, bool paired)
    {
        if (portal == null || portal.wallCollider == null)
            return;

        bool carved = IsCarvedWall(portal);
        if (paired && !carved)
        {
            Collider carvedCollider =
                CarveHostWall(portal.wallCollider, portal);
            if (carvedCollider != null)
                portal.wallCollider = carvedCollider;
        }
        else if (!paired && carved)
        {
            Collider source = ResolveCarveHostCollider(portal.wallCollider);
            ReleaseWallCarve(portal, portal.wallCollider);
            portal.wallCollider = source;
        }
    }

    /// <summary>
    /// Every point of the portal rectangle has to land on the host surface,
    /// with the same 4 HU probe Source uses.
    /// </summary>
    private bool OverhangPointsOnSurface(
        Vector3[] testPoints, float forgiveness)
    {
        Collider validationWall = GetWallValidationCollider(wallCollider);
        for (int i = 0; i < testPoints.Length; ++i)
        {
            // Source traces from corner + forward to corner - forward and
            // rejects a startsolid/no-surface result. Unity cannot detect
            // exits from inside a BoxCollider, so trace the same 4 HU interval
            // from the traversable side into the host wall instead.
            Vector3 point = testTransform.TransformPoint(testPoints[i]);
            Ray surfaceProbe = new Ray(
                point - testTransform.forward * forgiveness,
                testTransform.forward);
            if (!RaycastValidationCollider(
                    validationWall, surfaceProbe, forgiveness * 2f, out _))
                return false;
        }

        return true;
    }

    private bool FixOverhangs()
    {
        Vector3 halfSize = GetPortalHalfSize();
        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        float forgiveness = SourcePortalBumpForgivenessHu / unit;
        // IsPortalOnValidSurface tests the center plus four corners inset by
        // PORTAL_BUMP_FORGIVENESS * 1.1, not the exact rectangle corners.
        float inset = forgiveness * 1.1f;
        float x = Mathf.Max(0.0001f, halfSize.x - inset);
        float y = Mathf.Max(0.0001f, halfSize.y - inset);
        Vector3[] testPoints =
        {
            Vector3.zero,
            new Vector3(-x, y, 0f),
            new Vector3(x, y, 0f),
            new Vector3(-x, -y, 0f),
            new Vector3(x, -y, 0f)
        };

        if (OverhangPointsOnSurface(testPoints, forgiveness))
            return true;

        // Source rejects a portal that hangs off the surface, which makes the
        // strip between the ground and a portal already sitting above it
        // unaimable: the shot lands there, the lower corners fall past the
        // surface's bottom edge, and the whole click is dropped. Slide along
        // the portal's own up and right instead and keep the nearest offset
        // whose points all land on the host, so a shot near an edge resolves
        // to the closest legal pose rather than to nothing.
        Vector3 originalPosition = testTransform.position;
        Vector3 slideUp = testTransform.up;
        Vector3 slideRight = testTransform.right;
        Vector3[] slideDirections =
        {
            slideUp, -slideUp, slideRight, -slideRight
        };
        // A portal whose centre sits on the surface edge only has to travel
        // one half-size to bring that edge onto the surface. World half-size:
        // the slide is a world-space translation while the test points above
        // are local.
        Vector3 worldHalfSize = GetPortalHalfSizeWorld();
        float[] slideLimits =
        {
            worldHalfSize.y, worldHalfSize.y,
            worldHalfSize.x, worldHalfSize.x
        };

        const int SlideSteps = 16;
        float bestDistance = float.PositiveInfinity;
        Vector3 bestPosition = originalPosition;
        for (int d = 0; d < slideDirections.Length; ++d)
        {
            for (int step = 1; step <= SlideSteps; ++step)
            {
                float distance = slideLimits[d] * step / SlideSteps;
                if (distance >= bestDistance)
                    break;

                testTransform.position =
                    originalPosition + slideDirections[d] * distance;
                if (!OverhangPointsOnSurface(testPoints, forgiveness))
                    continue;

                bestDistance = distance;
                bestPosition = testTransform.position;
                break;
            }
        }

        testTransform.position = bestPosition;
        return bestDistance < float.PositiveInfinity;
    }

    /// <summary>
    /// Source's VerifyPortalPlacement snaps a wall portal downward when its
    /// lower edge is within 1.5 HU of the floor but not already touching it.
    /// </summary>
    private void ApplySourceFloorSnap()
    {
        if (testTransform == null ||
            Vector3.Dot(testTransform.up, Vector3.up) <= 0.7f)
            return;

        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        float smallForward = 0.05f / unit;
        float halfHeight = GetPortalHalfSizeWorld().y;
        Vector3 origin = testTransform.position -
            testTransform.forward * smallForward;
        float probeDistance = halfHeight + 1.5f / unit;
        if (!Physics.Raycast(origin, -testTransform.up, out RaycastHit floorHit,
                probeDistance, placementMask, QueryTriggerInteraction.Ignore) ||
            floorHit.collider == portalCollider)
            return;

        float verifyDistance = halfHeight - 0.1f / unit;
        if (verifyDistance > 0f &&
            Physics.Raycast(origin, -testTransform.up, verifyDistance,
                placementMask, QueryTriggerInteraction.Ignore))
            return;

        testTransform.position = floorHit.point +
            testTransform.up * halfHeight +
            testTransform.forward * smallForward;
    }

    private bool FixIntersects()
    {
        Vector3[] testDirections =
        {
            Vector3.right,
            -Vector3.right,
            Vector3.up,
            -Vector3.up
        };
        Vector3 halfSize = GetPortalHalfSizeWorld();
        float[] testDistances = { halfSize.x, halfSize.x, halfSize.y, halfSize.y };

        for (int i = 0; i < testDirections.Length; ++i)
        {
            RaycastHit hit;
            Vector3 raycastPosition = testTransform.TransformPoint(
                new Vector3(0f, 0f, -0.1f));
            Vector3 raycastDirection = testTransform.TransformDirection(
                testDirections[i]);

            if (Physics.Raycast(raycastPosition, raycastDirection, out hit,
                testDistances[i], placementMask,
                QueryTriggerInteraction.Ignore))
            {
                Vector3 offset = hit.point - raycastPosition;
                Vector3 correction = -raycastDirection *
                    (testDistances[i] - offset.magnitude);
                testTransform.Translate(correction, Space.World);
            }
        }

        return true;
    }

    /// <summary>
    /// Full hierarchy path plus collider type, so a placement rejection names
    /// the exact object instead of an ambiguous "Cube" that could be the host,
    /// a neighbour, or a carve-generated mesh.
    /// </summary>
    private static string DescribeCollider(Collider collider)
    {
        if (collider == null)
            return "none";

        string path = collider.name;
        Transform parent = collider.transform.parent;
        while (parent != null)
        {
            path = parent.name + "/" + path;
            parent = parent.parent;
        }

        return path + "(" + collider.GetType().Name + ")";
    }

    private bool CheckOverlap(bool logFailure = true)
    {
        Vector3 halfSize = GetPortalHalfSizeWorld();
        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        float halfDepth = SourcePortalHalfDepthHu / unit;
        float forgiveness = SourcePortalBumpForgivenessHu / unit;
        Vector3 checkExtents = new Vector3(
            halfSize.x - forgiveness,
            halfSize.y - forgiveness,
            halfDepth);
        // Unity cannot hit a collider from a ray that starts inside it.
        // Keep the probe origin on the traversable side and shoot into the
        // host wall, matching the original working placement probe.
        Vector3 portalFront = testTransform.position -
            testTransform.forward * halfDepth;
        // The plate's back face lies exactly on the host surface, so the check
        // box used to end in that same plane. Anything coplanar with it - the
        // carve's MeshCollider on the host, or a neighbouring piece of the
        // same slope - then registered as an overlap and rejected shots that
        // were nowhere near solid geometry, which is why aiming just below an
        // existing portal did nothing. Test only the volume genuinely in front
        // of the surface: start the box at the plate's front face instead.
        Vector3 checkCenter = testTransform.position -
            testTransform.forward * (halfDepth * 2f);
        Vector3[] checkPositions =
        {
            portalFront,
            portalFront - testTransform.right * halfSize.x -
                testTransform.up * halfSize.y,
            portalFront - testTransform.right * halfSize.x +
                testTransform.up * halfSize.y,
            portalFront + testTransform.right * halfSize.x -
                testTransform.up * halfSize.y,
            portalFront + testTransform.right * halfSize.x +
                testTransform.up * halfSize.y
        };

        Collider validationWall = GetWallValidationCollider(wallCollider);
        // The carve puts its generated MeshCollider on the SAME GameObject as
        // the authored collider, so it is neither the wallCollider reference
        // nor a child of it, and the exclusion below missed it. Its surface is
        // coplanar with the authored one and the check box's back face lies in
        // that same plane, so every shot over solid host geometry - i.e. any
        // re-placement that is not exactly on top of the existing hole -
        // reported an overlap with its own host and was rejected. Compare the
        // GameObject instead of the reference: everything on the host object
        // is the host, however many colliders the carve has added to it.
        GameObject hostObject =
            wallCollider != null ? wallCollider.gameObject : null;
        Collider[] intersections = Physics.OverlapBox(
            checkCenter, checkExtents, testTransform.rotation,
            placementMask, QueryTriggerInteraction.Ignore);
        for (int i = 0; i < intersections.Length; ++i)
        {
            if (intersections[i] == portalCollider ||
                intersections[i] == wallCollider ||
                intersections[i] == validationWall)
                continue;
            if (hostObject != null &&
                intersections[i].gameObject == hostObject)
                continue;
            if (wallCollider != null &&
                intersections[i].transform.IsChildOf(wallCollider.transform))
                continue;

            // Touching the host plane is not an overlap: the plate's back face
            // lies on that plane by construction, and a second piece of the
            // same slope is usually coplanar with it. Reject only when the
            // blocker actually reaches into the volume in front of the
            // surface, which is where the plate really lives.
            Vector3 closest = intersections[i].ClosestPoint(checkCenter);
            float inFront = Vector3.Dot(
                closest - testTransform.position, -testTransform.forward);
            if (inFront <= halfDepth)
                continue;

            if (logFailure)
            {
                Debug.Log("[PortalPlace]   overlap: " +
                    DescribeCollider(intersections[i]) +
                    " inFront=" + inFront.ToString("F3") +
                    " bounds=" + intersections[i].bounds +
                    " host=" + DescribeCollider(wallCollider) +
                    " box=" + checkCenter.ToString("F3") +
                    " ext=" + checkExtents.ToString("F3") +
                    " plane=" + testTransform.position.ToString("F3"));
            }
            return false;
        }

        Vector3 wallProbe = testTransform.forward * (halfDepth * 2f);
        for (int i = 1; i < checkPositions.Length; ++i)
        {
            // Probe the authored wall, not the carved collision. The hole is
            // real geometry, so a corner that sits over an existing portal
            // would shoot straight through it and reject a perfectly good
            // re-placement.
            Ray cornerProbe = new Ray(checkPositions[i], wallProbe.normalized);
            if (!RaycastValidationCollider(
                    validationWall, cornerProbe, wallProbe.magnitude, out _))
            {
                if (logFailure)
                {
                    Debug.Log("[PortalPlace]   corner " + i +
                        " has no host behind it");
                }
                return false;
            }
        }

        return true;
    }

    /// <summary>
    /// A portal the player cannot walk into is not worth placing. The teleport
    /// fires only once the hull's centre gets past the plane, so the recess
    /// behind the plate has to be deep enough - and empty enough - for the hull
    /// to reach that point. Anything that reaches into that recess and is not
    /// the host brush itself (which the carve removes) stops the hull short:
    /// the portal would look placed and never fire.
    /// </summary>
    /// <remarks>
    /// The volume tested is the hull cross-section swept backwards from the
    /// plane by the recess depth, not the portal opening. The opening is
    /// 64 x 112 HU while the hull is only 32 wide and 54 or 72 tall, so testing
    /// the opening rejected placements the player could walk into.
    /// </remarks>
    private bool CheckBackClearance(bool logFailure = true)
    {
        Vector3 normal = GetPortalPlaneNormal(this);
        if (normal.sqrMagnitude < 0.000001f)
            return true;
        normal.Normalize();

        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        // A shallow surface - a floor, or anything within 45 degrees of one -
        // forces the crouch on entry, and the duck hull is only 54 HU tall, so
        // it only has to sink half of that to reach the plane. A steeper
        // surface is entered standing and needs the full half-height.
        float halfHeightHu = Mathf.Abs(normal.y) >= SourceShallowSurfaceDot
            ? SourcePlayerDuckHalfHeightHu
            : SourcePlayerHalfHeightHu;
        // Placement asks for the full recess the standing/duck hull needs
        // behind the plate (0.674 UU on a shallow slope with the duck hull).
        // Kept at the full value rather than reduced by the crossing relief.
        float recess = GetPortalRecessDepthWorld(this, halfHeightHu);
        Vector3 extents = new Vector3(
            SourcePlayerHalfWidthHu / unit,
            halfHeightHu / unit,
            recess * 0.5f);
        // transform.forward points into the host (GetPortalPlaneNormal negates
        // it), so the recess is the volume from the plane along +forward.
        Vector3 center = testTransform.position +
            testTransform.forward * (recess * 0.5f);

        WallCarveState state = null;
        if (wallCollider != null)
            CarvedWalls.TryGetValue(wallCollider.gameObject, out state);
        Collider sourceCollider = state != null ? state.SourceCollider : null;
        Collider carvedCollider = state != null ? state.CarvedCollider : null;
        Collider validationWall = GetWallValidationCollider(wallCollider);
        GameObject hostObject = wallCollider != null
            ? wallCollider.gameObject
            : null;

        Collider blocker = null;
        Collider[] overlaps = Physics.OverlapBox(center, extents,
            testTransform.rotation, Physics.AllLayers,
            QueryTriggerInteraction.Ignore);
        for (int i = 0; i < overlaps.Length; ++i)
        {
            Collider other = overlaps[i];
            if (other == null || other == portalCollider ||
                other == wallCollider || other == validationWall ||
                other == sourceCollider || other == carvedCollider)
                continue;
            // The host brush's own hierarchy is what the carve replaces, so
            // its volume in the recess is expected. Its children are included:
            // a brush split across child colliders would otherwise block every
            // placement on it.
            if (hostObject != null && other.gameObject != hostObject &&
                other.transform.IsChildOf(hostObject.transform))
                continue;
            // A collider sitting inside the host volume but not on the host's
            // authored collider survives the carve - the rebuild replaces the
            // authored collider only - so it stays solid exactly where the hole
            // should be. That is the "nested inside" case; treat it as a
            // blocker even though it shares the host object.
            blocker = other;
            break;
        }

        if (blocker == null)
            return true;

        if (logFailure)
        {
            float behind = -Vector3.Dot(
                blocker.ClosestPoint(testTransform.position) -
                    testTransform.position,
                normal);
            Debug.Log("[PortalPlace]   back clearance: " +
                DescribeCollider(blocker) +
                " reaches " + behind.ToString("F3") +
                " UU behind the plate, recess needs " +
                recess.ToString("F3") + " UU for the " +
                (2f * halfHeightHu).ToString("F0") + " HU hull" +
                " (host=" + DescribeCollider(wallCollider) + ")");
        }
        return false;
    }

    /// <summary>
    /// A shot that lands where the plate would clip something is not worth
    /// dropping. Slide along the surface, nearest offset first, and take the
    /// first pose that passes the surface, overlap and back-clearance tests, so
    /// the click resolves to a portal right next to where it was aimed.
    /// </summary>
    /// <remarks>
    /// Without this, whether a click works depends on things the player cannot
    /// see: the portal's roll comes from the camera, so aiming at "the same
    /// spot" yields a slightly different rectangle every time, and a
    /// successful placement rebuilds the host's carve, so the next click faces
    /// a different set of colliders. That reads as random. Searching removes
    /// the coin flip - a click either places near the aim or reports a real
    /// obstruction.
    /// </remarks>
    private bool TrySlideOutOfOverlap()
    {
        Vector3 halfSize = GetPortalHalfSizeWorld();
        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        float forgiveness = SourcePortalBumpForgivenessHu / unit;
        float inset = forgiveness * 1.1f;
        Vector3 localHalfSize = GetPortalHalfSize();
        float x = Mathf.Max(0.0001f, localHalfSize.x - inset);
        float y = Mathf.Max(0.0001f, localHalfSize.y - inset);
        Vector3[] testPoints =
        {
            Vector3.zero,
            new Vector3(-x, y, 0f),
            new Vector3(x, y, 0f),
            new Vector3(-x, -y, 0f),
            new Vector3(x, -y, 0f)
        };

        Vector3 originalPosition = testTransform.position;
        Vector3 slideUp = testTransform.up;
        Vector3 slideRight = testTransform.right;
        Vector3[] directions =
        {
            slideUp, -slideUp, slideRight, -slideRight
        };

        const int Steps = 8;
        float stepSize = Mathf.Max(halfSize.x, halfSize.y) / Steps;
        for (int step = 1; step <= Steps; ++step)
        {
            for (int d = 0; d < directions.Length; ++d)
            {
                testTransform.position =
                    originalPosition + directions[d] * (stepSize * step);
                if (!OverhangPointsOnSurface(testPoints, forgiveness))
                    continue;
                if (!CheckOverlap(false))
                    continue;
                if (!CheckBackClearance(false))
                    continue;

                Debug.Log("[PortalPlace] slid " +
                    (testTransform.position - originalPosition).magnitude
                        .ToString("F2") + " UU to a clear pose");
                return true;
            }
        }

        testTransform.position = originalPosition;
        return false;
    }

    public void RemovePortal()
    {
        Collider ignoredWall = wallCollider;
        ReleaseWallCarve(this, ignoredWall);
        ClearPortalOccupants();
        wallCollider = null;
        attachmentTransform = null;
        isPlaced = false;
        placeEabled = true;
        gameObject.SetActive(false);
    }

    /// <summary>
    /// Forces the portal trigger collider to Source's 64 x 112 x 4 HU
    /// dimensions regardless of the authored prefab scale.
    /// </summary>
    private void ApplySourcePortalSize()
    {
        BoxCollider box = portalCollider as BoxCollider;
        if (box == null)
            return;

        Vector3 scale = Abs(transform.lossyScale);
        float unit = PortalTransformMath.HammerUnitsPerUnityUnit;
        box.size = new Vector3(
            2f * SourcePortalHalfWidthHu / unit /
                Mathf.Max(0.000001f, scale.x),
            2f * SourcePortalHalfHeightHu / unit /
                Mathf.Max(0.000001f, scale.y),
            2f * SourcePortalHalfDepthHu / unit /
                Mathf.Max(0.000001f, scale.z));
    }

    private static Collider ResolveCarveHostCollider(Collider collider)
    {
        if (collider == null)
            return null;

        WallCarveState state;
        return CarvedWalls.TryGetValue(collider.gameObject, out state) &&
               state.SourceCollider != null
            ? state.SourceCollider
            : collider;
    }

    private static Collider CarveHostWall(Collider hitWall, Portal portal)
    {
        // Always carve from the original host collider. If this wall was
        // already carved, `hitWall` may be the generated MeshCollider; that
        // object gets destroyed by ReleaseWallCarve before the rebuild.
        hitWall = ResolveCarveHostCollider(hitWall);
        GameObject wallObject = hitWall != null ? hitWall.gameObject : null;
        if (wallObject == null || portal == null)
            return hitWall;

        WallCarveState state;
        if (!CarvedWalls.TryGetValue(wallObject, out state))
        {
            BoxCollider sourceBox = hitWall as BoxCollider;
            if (sourceBox == null)
                sourceBox = hitWall.GetComponent<BoxCollider>();

            Mesh sourceMesh = null;
            if (sourceBox == null)
            {
                MeshCollider sourceMeshCollider = hitWall as MeshCollider;
                if (sourceMeshCollider == null)
                    sourceMeshCollider = hitWall.GetComponent<MeshCollider>();
                if (sourceMeshCollider != null)
                    sourceMesh = sourceMeshCollider.sharedMesh;
            }

            if (sourceBox == null && sourceMesh == null)
                return hitWall;

            state = new WallCarveState
            {
                SourceCollider = hitWall,
                SourceBox = sourceBox,
                SourceMesh = sourceMesh
            };
            CarvedWalls.Add(wallObject, state);
        }

        if (!state.Owners.Contains(portal))
            state.Owners.Add(portal);

        if (!RebuildCarvedWall(state) || state.CarvedCollider == null)
        {
            // Neither carve path could build geometry. The host keeps its
            // authored collider, so the aperture filter still lets a fitting
            // hull through - but there is no visible hole, and a hull that does
            // not fit is simply blocked. Surface it instead of failing quietly:
            // the usual cause is a mesh without Read/Write enabled.
            Debug.LogWarning("[PortalCarve] no carve for " + hitWall.name +
                " host=" + (state.SourceBox != null ? "Box" : "Mesh") +
                " readable=" + (state.SourceMesh == null ||
                    state.SourceMesh.isReadable) +
                ": wall stays solid, no visible hole");
            return hitWall;
        }

        // The carved MeshCollider is the wall's collision from now on. The
        // portal stores it as its host wall so IsCarvedWall() is true and the
        // aperture filter stays out of the way: the hole is real geometry.
        return state.CarvedCollider;
    }

    private static void ReleaseWallCarve(Portal portal, Collider wallCollider)
    {
        if (portal == null)
            return;

        WallCarveState state = FindWallState(portal, wallCollider);
        if (state == null)
            return;

        state.Owners.Remove(portal);
        if (state.Owners.Count > 0)
        {
            RebuildCarvedWall(state);
            return;
        }

        if (state.CarvedCollider != null)
        {
            PortalPatchColliders.Remove(state.CarvedCollider);
            if (Application.isPlaying)
                UnityEngine.Object.Destroy(state.CarvedCollider);
            else
                UnityEngine.Object.DestroyImmediate(state.CarvedCollider);
            state.CarvedCollider = null;
        }
        if (state.CarvedMesh != null)
        {
            if (Application.isPlaying)
                UnityEngine.Object.Destroy(state.CarvedMesh);
            else
                UnityEngine.Object.DestroyImmediate(state.CarvedMesh);
            state.CarvedMesh = null;
        }
        if (state.SourceCollider != null)
        {
            PortalCarveDebugGizmo gizmo = state.SourceCollider.gameObject
                .GetComponent<PortalCarveDebugGizmo>();
            if (gizmo != null)
            {
                if (Application.isPlaying)
                    UnityEngine.Object.Destroy(gizmo);
                else
                    UnityEngine.Object.DestroyImmediate(gizmo);
            }
            state.SourceCollider.enabled = true;
        }

        if (state.SourceCollider != null)
            CarvedWalls.Remove(state.SourceCollider.gameObject);
        Physics.SyncTransforms();
    }

    // Placement validates against the full wall brush. Once a wall has been
    // carved, its live collider is a mesh with a hole; using that mesh for the
    // five-point surface test would make a portal look unsupported when it is
    // actually being moved across its own old opening.
    private static Collider GetWallValidationCollider(Collider wallCollider)
    {
        WallCarveState state;
        if (wallCollider != null &&
            CarvedWalls.TryGetValue(wallCollider.gameObject, out state) &&
            state.SourceCollider != null)
            return state.SourceCollider;
        return wallCollider;
    }

    private static bool RaycastValidationCollider(
        Collider collider,
        Ray ray,
        float maxDistance,
        out RaycastHit hit)
    {
        hit = default;
        if (collider == null)
            return false;

        // A carved wall disables its original collider. Direct Collider.Raycast
        // is used for placement validation, and temporarily enabling the
        // source collider keeps re-placement on the same wall working.
        bool wasEnabled = collider.enabled;
        if (!wasEnabled)
            collider.enabled = true;
        try
        {
            return collider.Raycast(ray, out hit, maxDistance);
        }
        finally
        {
            if (!wasEnabled)
                collider.enabled = false;
        }
    }

    /// <summary>
    /// Placement probes must see the wall the level author built, not the
    /// carved collision. The hole is real geometry now, so a shot aimed at an
    /// existing portal passes straight through it, the placement ray finds
    /// nothing, and the click is dropped - which is what made re-placing a
    /// portal take several tries. Source keeps its hole in a separate
    /// collideable that the placement trace filters out; the equivalent here
    /// is to swap the carve out for the length of the probe.
    /// </summary>
    public static void BeginPlacementProbe()
    {
        foreach (KeyValuePair<GameObject, WallCarveState> pair in CarvedWalls)
        {
            WallCarveState state = pair.Value;
            if (state.CarvedCollider == null)
                continue;
            state.CarvedCollider.enabled = false;
            if (state.SourceCollider != null)
                state.SourceCollider.enabled = true;
        }
        Physics.SyncTransforms();
    }

    public static void EndPlacementProbe()
    {
        foreach (KeyValuePair<GameObject, WallCarveState> pair in CarvedWalls)
        {
            WallCarveState state = pair.Value;
            if (state.CarvedCollider == null)
                continue;
            if (state.SourceCollider != null)
                state.SourceCollider.enabled = false;
            state.CarvedCollider.enabled = true;
        }
        Physics.SyncTransforms();
    }

    private static WallCarveState FindWallState(
        Portal portal, Collider wallCollider)
    {
        if (wallCollider != null)
        {
            WallCarveState byCollider;
            if (CarvedWalls.TryGetValue(
                    wallCollider.gameObject, out byCollider))
                return byCollider;
        }

        foreach (KeyValuePair<GameObject, WallCarveState> pair in CarvedWalls)
        {
            if (pair.Value.Owners.Contains(portal))
                return pair.Value;
        }
        return null;
    }

    private static int GetPortalWallAxis(Portal portal, Transform wallTransform)
    {
        Vector3 forwardLocal = wallTransform.InverseTransformDirection(
            portal.transform.forward);
        int axis = 0;
        if (Mathf.Abs(forwardLocal.y) > Mathf.Abs(forwardLocal[axis]))
            axis = 1;
        if (Mathf.Abs(forwardLocal.z) > Mathf.Abs(forwardLocal[axis]))
            axis = 2;
        return Mathf.Abs(forwardLocal[axis]) >= 0.9f ? axis : -1;
    }

    private static float GetWallThicknessWorld(WallCarveState state, int axis)
    {
        float localThickness;
        if (state.SourceBox != null)
            localThickness = Mathf.Abs(state.SourceBox.size[axis]);
        else if (state.SourceMesh != null)
            localThickness = Mathf.Abs(state.SourceMesh.bounds.size[axis]);
        else
            return 0f;

        return localThickness *
            Mathf.Abs(state.SourceCollider.transform.lossyScale[axis]);
    }

    private static bool IsCarvedWall(Portal portal)
    {
        if (portal == null || portal.wallCollider == null)
            return false;

        WallCarveState state;
        return CarvedWalls.TryGetValue(
            portal.wallCollider.gameObject, out state) &&
            state.CarvedCollider == portal.wallCollider;
    }

    /// <summary>
    /// True when the collider is the carved collision mesh of a portal host.
    /// </summary>
    /// <remarks>
    /// Stuck recovery normally ignores portal hosts, because a hull resting on
    /// the aperture rim is a normal resting place and treating that contact as
    /// stuck zeroes the velocity every command. A carved host is different:
    /// its hole is real geometry, so a hull that penetrates it is genuinely
    /// straddling the rim. Leaving that invisible meant a hull that drifted
    /// into the rim after a teleport stayed frozen forever. Thin hosts keep the
    /// exemption - their hulls pass through the solid collider by design.
    /// </remarks>
    public static bool IsCarvedPortalHostCollider(Collider candidate)
    {
        if (candidate == null)
            return false;

        WallCarveState state;
        return CarvedWalls.TryGetValue(candidate.gameObject, out state) &&
            state.CarvedCollider == candidate;
    }

    /// <summary>
    /// The portal whose host wall (or a child of it) is the given collider.
    /// Diagnostics only: lets a stuck report say which portal owns the geometry
    /// that is holding the hull, and where the hull sits relative to that
    /// portal's plane and opening.
    /// </summary>
    public static Portal FindPortalHostingCollider(Collider candidate)
    {
        if (candidate == null)
            return null;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal portal = ActivePortals[i];
            if (portal == null || portal.wallCollider == null)
                continue;
            if (candidate == portal.wallCollider ||
                candidate.transform.IsChildOf(portal.wallCollider.transform))
                return portal;
        }

        return null;
    }

