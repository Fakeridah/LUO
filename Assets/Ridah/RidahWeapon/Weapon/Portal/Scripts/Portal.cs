[RequireComponent(typeof(Collider))]
public class Portal : MonoBehaviour
{
    private static readonly List<Portal> ActivePortals = new List<Portal>();

    private struct PortalHole
    {
        public Portal Owner;
        public int Axis;
        public int A;
        public int B;
        public Vector3 Min;
        public Vector3 Max;
        public float BackAxis;
        public float BackNormalSign;
        // A floor/ceiling portal is cut straight through. The blind recess is
        // only deep enough for the hull's horizontal half-depth; a hull
        // entering a horizontal portal has to descend its whole standing
        // half-height (0.686 UU) past the plane, so a recess floor would stop
        // it short and the portal would never fire - and it would read as a
        // pit the player sinks into.
        public bool Through;
    }

    // A clipping plane in host-wall local space. The kept half-space is
    // Dot(Normal, point) <= Distance; Normal points into the material that is
    // removed, matching Source's outward-facing CPolyhedron planes.
