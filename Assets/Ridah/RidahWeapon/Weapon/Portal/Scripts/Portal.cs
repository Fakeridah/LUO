    }

    private static Portal FindBackCapOwner(
        int triangleIndex,
        WallCarveState state)
    {
        if (state == null || triangleIndex < 0)
            return null;

        for (int i = 0; i < state.BackCaps.Count; ++i)
        {
            BackCapRange range = state.BackCaps[i];
            if (triangleIndex >= range.TriangleStart &&
                triangleIndex < range.TriangleStart + range.TriangleCount)
                return range.Owner;
        }
        return null;
    }

    /// <summary>
    /// Replaces the host wall's collision with a mesh that has a real hole in
    /// it, exactly like Source carving the BSP brush.
    ///
    /// This is the only structure that can work. An aperture filter cannot
    /// emulate a hole: the hull has to pass THROUGH solid wall material, so it
    /// is genuinely overlapping the wall for the whole crossing. PhysX reports
    /// an already-overlapping box as a zero-distance BoxCast hit, TracePlayerBBox
    /// then returns fraction 0, TrySlideMove makes no progress, allFraction
    /// stays 0 and velocity is zeroed - the player freezes. Widening the filter
    /// instead lets the hull walk through the wall beside the portal. A real
    /// hole has neither failure mode: there is no material to overlap, and the
    /// hole's own walls stop a hull that drifts sideways.
    ///
    /// The carve is a blind recess: the hole starts on the traversable face and
    /// stops one player half-depth plus portal depth and bump forgiveness
    /// behind it, so the hull centre can always reach the portal plane. The
    /// opposite face is never cut, which is what makes the reverse side solid.
    ///
    /// BoxCollider hosts are thickened along the portal normal (away from the
    /// traversable face, collision only, the rendered wall is untouched) just
    /// enough to hold that recess. Without it a 0.1 UU wall cannot contain the
    /// 0.381 UU recess and the hull would hit the recess floor before the
    /// plane, so the portal would never fire.
    /// </summary>
    private static bool RebuildCarvedWall(WallCarveState state)
    {
        Collider sourceCollider = state.SourceCollider;
        if (sourceCollider == null)
            return false;

        Vector3 boxMin;
        Vector3 boxMax;
        if (state.SourceBox != null)
        {
            boxMin = state.SourceBox.center - state.SourceBox.size * 0.5f;
            boxMax = state.SourceBox.center + state.SourceBox.size * 0.5f;
        }
        else if (state.SourceMesh != null)
        {
            boxMin = state.SourceMesh.bounds.min;
            boxMax = state.SourceMesh.bounds.max;
        }
        else
        {
            return false;
        }

        Transform wallTransform = sourceCollider.transform;

        for (int i = 0; i < state.Owners.Count; ++i)
        {
            Portal owner = state.Owners[i];
            if (owner == null)
                continue;
            int wallAxis = GetPortalWallAxis(owner, wallTransform);
            if (wallAxis < 0)
                // Same 0.9 threshold TryGetPortalHoleBounds uses, so this
                // skip and the "no hole at all" outcome below always agree:
                // a host that is not axis-aligned to its portal gets neither a
                // hole nor thickening, and the wall simply stays solid. Only
                // the optional thin-box thickening needs a host axis here.
                continue;

            // TryGetPortalHoleBounds cuts the full recess from the traversable
            // face, so the box needs that recess plus solid backing behind it.
            // The recess depth depends on the orientation - a floor needs the
            // full standing half-height, a slope a blend of half-height and
            // half-depth, a wall only the half-depth - so it is computed per
            // owner and the box is grown to the largest requirement across the
            // host's portals.
            float requiredRecessWorld = GetPortalRecessDepthWorld(owner);
            float requiredThicknessWorld = requiredRecessWorld + 0.06f;

            float axisScale = Mathf.Max(
                0.0001f, Mathf.Abs(wallTransform.lossyScale[wallAxis]));
            float requiredThicknessLocal =
                requiredThicknessWorld / axisScale;
            float currentThicknessLocal =
                boxMax[wallAxis] - boxMin[wallAxis];

            if (state.SourceBox != null)
            {
                if (currentThicknessLocal >= requiredThicknessLocal)
                    continue;

                Vector3 planeNormalLocal =
                    wallTransform.InverseTransformDirection(
                        GetPortalPlaneNormal(owner));
                float frontSign = Vector3.Dot(
                    planeNormalLocal, AxisDirection(wallAxis)) >= 0f
                    ? 1f
                    : -1f;
                if (frontSign > 0f)
                    boxMin[wallAxis] =
                        boxMax[wallAxis] - requiredThicknessLocal;
                else
                    boxMax[wallAxis] =
                        boxMin[wallAxis] + requiredThicknessLocal;
                continue;
            }

            // A MeshCollider host is a surface, not a volume, so it needs no
            // thickness at all: the blind recess is closed by its own floor
            // quad in BuildMeshCarvedWallMesh instead of by leftover solid
            // wall. That is what lets a zero-thickness polygon wall work, at
            // the same cost as a thickened thin box - the recess floor sits
            // behind the wall surface.
        }

        List<PortalHole> holes = new List<PortalHole>();
        for (int i = 0; i < state.Owners.Count; ++i)
        {
            Portal owner = state.Owners[i];
            if (owner == null)
                continue;

            PortalHole hole;
            if (TryGetPortalHoleBounds(
                    owner, wallTransform, boxMin, boxMax, out hole))
                holes.Add(hole);
        }

        // TEMPORARY PLACEMENT DIAGNOSTIC. One line per placement so the carve
        // geometry can be read back from Editor.log without the debug bridge.
        System.Text.StringBuilder diag = new System.Text.StringBuilder();
        diag.Append("[PortalCarve] wall=").Append(sourceCollider.name)
            .Append(" host=").Append(state.SourceBox != null ? "Box" : "Mesh")
            .Append(" scale=").Append(wallTransform.lossyScale)
            .Append(" boxMin=").Append(boxMin)
            .Append(" boxMax=").Append(boxMax)
            .Append(" holes=").Append(holes.Count);
        for (int i = 0; i < holes.Count; ++i)
        {
            diag.Append(" | axis=").Append(holes[i].Axis)
                .Append(" a=").Append(holes[i].A)
                .Append(" b=").Append(holes[i].B)
                .Append(" through=").Append(holes[i].Through)
                .Append(" min=").Append(holes[i].Min)
                .Append(" max=").Append(holes[i].Max)
                .Append(" normal=")
                .Append(holes[i].Owner != null
                    ? GetPortalPlaneNormal(holes[i].Owner).ToString()
                    : "null");
        }
        Debug.Log(diag.ToString());

        state.BackCaps.Clear();
        Mesh mesh;
        bool carvedFromHostAxes = holes.Count > 0;
        if (carvedFromHostAxes && state.SourceBox != null)
        {
            if (!BuildBoxCarvedWallMesh(
                    boxMin, boxMax, holes, state.BackCaps, out mesh))
                return false;
        }
        else if (carvedFromHostAxes)
        {
            if (!BuildMeshCarvedWallMesh(
                    state.SourceMesh, boxMin, boxMax, holes,
                    state.BackCaps, out mesh))
                return false;
        }
        else
        {
            // TryGetPortalHoleBounds needs the portal plane to line up with a
            // host axis (|dot| >= 0.9). A BoxCollider host can never fail that
            // - its face normal is a local axis - but an arbitrary mesh surface
            // can, and failing there used to leave the wall completely solid
            // with no visible hole. The portal-aligned carve works in world
            // space and needs no host axis, so use it as the fallback.
            List<PortalHoleWorld> worldHoles = new List<PortalHoleWorld>();
            for (int i = 0; i < state.Owners.Count; ++i)
            {
                Portal owner = state.Owners[i];
                if (owner == null)
                    continue;

                PortalHoleWorld worldHole;
                if (TryGetWorldHole(
                        owner, wallTransform, boxMin, boxMax, out worldHole))
                    worldHoles.Add(worldHole);
            }

            if (worldHoles.Count == 0 ||
                !BuildWorldCarvedMesh(
                    boxMin, boxMax, state.SourceMesh, worldHoles,
                    wallTransform, out mesh))
                return false;

            // The world-space builder does not record back caps, so the recess
            // floor stays ordinary solid geometry. That matches what the
            // movement filter wants now anyway: the cap is only ever reached
            // after the hull centre has already crossed the plane.
            Debug.Log("[PortalCarve] host axes disagree with the portal plane; " +
                "used the portal-aligned carve for " + sourceCollider.name);
        }

        if (state.CarvedCollider == null)
        {
            state.CarvedCollider =
                sourceCollider.gameObject.AddComponent<MeshCollider>();
        }
        state.CarvedCollider.convex = false;
        state.CarvedCollider.isTrigger = sourceCollider.isTrigger;
        state.CarvedCollider.sharedMesh = null;
        state.CarvedCollider.sharedMesh = mesh;
        Debug.Log("[PortalCarve] mesh verts=" + mesh.vertexCount +
            " bounds=" + mesh.bounds);
        state.CarvedCollider.enabled = true;

        // TEMPORARY: show the generated collision mesh in the Scene view.
        PortalCarveDebugGizmo gizmo =
            sourceCollider.gameObject.GetComponent<PortalCarveDebugGizmo>();
        if (gizmo == null)
        {
            gizmo = sourceCollider.gameObject
                .AddComponent<PortalCarveDebugGizmo>();
            Debug.Log("[PortalCarve] debug gizmo attached to " +
                sourceCollider.name);
        }
        gizmo.CarvedCollider = state.CarvedCollider;
        if (state.CarvedMesh != null && state.CarvedMesh != mesh)
            UnityEngine.Object.Destroy(state.CarvedMesh);
        state.CarvedMesh = mesh;
        sourceCollider.enabled = false;
        Physics.SyncTransforms();
        return true;
    }

    /// <summary>
    /// Builds the collision-only local patch for one host wall: for every
    /// portal on that wall, a CLOSED SOLID slab with a THROUGH opening cut
    /// into it. It is a watertight manifold - front annulus, four hole walls,
    /// back annulus and four outer side walls - so PhysX can always tell
    /// "outside the solid" from "inside the hole" and a grazing hull is
    /// resolved by pushing it back to the near side instead of jamming.
    ///
    /// Two constraints shape it:
    ///  * No floor. Source teleports on hull-centre crossing, so the hull must
    ///    advance a full 0.305 UU half-depth past the plane; any floor closer
    ///    than that stops the hull short and the portal never fires.
    ///  * Entirely inside the host wall. A patch that pokes out behind a thin
    ///    wall adds a second collision surface in open space, which is what
    ///    made thin walls stick while thick walls were fine.
    ///
    /// The hole is also widened past the passage test (FitsPortalOpening), so
    /// a hull that is allowed to pass never overlaps the hole walls at all;
    /// the patch only becomes real geometry if the hull tries to leave the
    /// opening sideways.
    /// </summary>
    private static bool BuildSolidRecessPatch(
        Transform wallTransform,
        Vector3 boxMin,
        Vector3 boxMax,
        List<PortalHole> holes,
        out Mesh mesh)
    {
        mesh = null;
        if (holes == null || holes.Count == 0)
            return false;

        List<Vector3> vertices = new List<Vector3>();
        List<Vector3> normals = new List<Vector3>();
        List<Vector2> uvs = new List<Vector2>();
        List<int> triangles = new List<int>();
        Vector3 boxSize = boxMax - boxMin;
        Vector3 scale = wallTransform != null
            ? Abs(wallTransform.lossyScale)
            : Vector3.one;

        for (int i = 0; i < holes.Count; ++i)
        {
            PortalHole hole = holes[i];
            int axis = hole.Axis;
            int a = hole.A;
            int b = hole.B;

            float front = hole.BackAxis;

            // sign points from the wall toward the traversable side.
            float sign = hole.BackNormalSign >= 0f ? 1f : -1f;
            Vector3 frontNormal = AxisDirection(axis) * sign;
            Vector3 backNormal = -frontNormal;

            float axisScale = Mathf.Max(0.0001f, scale[axis]);
            float aScale = Mathf.Max(0.0001f, scale[a]);
            float bScale = Mathf.Max(0.0001f, scale[b]);
            // Keep the patch just behind the wall's own faces, so the host
            // wall always wins the first contact on either side.
            float frontInset = PatchFrontInset / axisScale;
            float backInset = PatchFrontInset / axisScale;
            float holeClearA = PatchHoleClearance / aScale;
            float holeClearB = PatchHoleClearance / bScale;
            float marginA = PatchOuterMargin / aScale;
            float marginB = PatchOuterMargin / bScale;

            // The patch is a THROUGH opening with no floor, and it must stay
            // entirely inside the host wall.
            //
            // No floor: Source teleports on hull-centre crossing, so the hull
            // has to advance a full half-depth (0.305 UU) past the plane. Any
            // floor closer than that stops the hull before the crossing and
            // the portal simply never fires - which is exactly what a
            // wall-thickness-clamped blind recess does.
            //
            // Inside the wall: a patch that pokes out behind a thin wall is a
            // second collision surface in open space, which is what made thin
            // walls stick while 1 UU walls were fine. Buried, thin and thick
            // behave identically.
            float thickness = Mathf.Abs(boxMax[axis] - boxMin[axis]);
            float available = thickness - frontInset - backInset;
            if (available <= 0.01f)
                continue;

            float frontPlane = front - sign * frontInset;
            float backPlane = frontPlane - sign * available;

            float aHoleMin = hole.Min[a] - holeClearA;
            float aHoleMax = hole.Max[a] + holeClearA;
            float bHoleMin = hole.Min[b] - holeClearB;
            float bHoleMax = hole.Max[b] + holeClearB;
            float aOutMin = aHoleMin - marginA;
            float aOutMax = aHoleMax + marginA;
            float bOutMin = bHoleMin - marginB;
            float bOutMax = bHoleMax + marginB;

            // Front annulus: closes the solid around the opening.
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMin, bHoleMax,
                frontPlane, aOutMax, bHoleMax,
                frontPlane, aOutMax, bOutMax,
                frontPlane, aOutMin, bOutMax,
                frontNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMin, bOutMin,
                frontPlane, aOutMax, bOutMin,
                frontPlane, aOutMax, bHoleMin,
                frontPlane, aOutMin, bHoleMin,
                frontNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMin, bHoleMin,
                frontPlane, aHoleMin, bHoleMin,
                frontPlane, aHoleMin, bHoleMax,
                frontPlane, aOutMin, bHoleMax,
                frontNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aHoleMax, bHoleMin,
                frontPlane, aOutMax, bHoleMin,
                frontPlane, aOutMax, bHoleMax,
                frontPlane, aHoleMax, bHoleMax,
                frontNormal);

            // Hole walls: the through opening. Widened past the passage test
            // so a hull that is allowed to pass never touches them.
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aHoleMin, bHoleMin,
                backPlane, aHoleMin, bHoleMin,
                backPlane, aHoleMin, bHoleMax,
                frontPlane, aHoleMin, bHoleMax,
                AxisDirection(a));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aHoleMax, bHoleMax,
                backPlane, aHoleMax, bHoleMax,
                backPlane, aHoleMax, bHoleMin,
                frontPlane, aHoleMax, bHoleMin,
                -AxisDirection(a));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aHoleMax, bHoleMin,
                backPlane, aHoleMax, bHoleMin,
                backPlane, aHoleMin, bHoleMin,
                frontPlane, aHoleMin, bHoleMin,
                AxisDirection(b));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aHoleMin, bHoleMax,
                backPlane, aHoleMin, bHoleMax,
                backPlane, aHoleMax, bHoleMax,
                frontPlane, aHoleMax, bHoleMax,
                -AxisDirection(b));

            // Back annulus: closes the solid on the reverse face. The wall's
            // own collider still blocks reverse entry, so the through opening
            // stays one-way without a floor here.
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                backPlane, aOutMin, bHoleMax,
                backPlane, aOutMax, bHoleMax,
                backPlane, aOutMax, bOutMax,
                backPlane, aOutMin, bOutMax,
                backNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                backPlane, aOutMin, bOutMin,
                backPlane, aOutMax, bOutMin,
                backPlane, aOutMax, bHoleMin,
                backPlane, aOutMin, bHoleMin,
                backNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                backPlane, aOutMin, bHoleMin,
                backPlane, aHoleMin, bHoleMin,
                backPlane, aHoleMin, bHoleMax,
                backPlane, aOutMin, bHoleMax,
                backNormal);
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                backPlane, aHoleMax, bHoleMin,
                backPlane, aOutMax, bHoleMin,
                backPlane, aOutMax, bHoleMax,
                backPlane, aHoleMax, bHoleMax,
                backNormal);

            // Outer side walls: finish the manifold.
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMin, bOutMax,
                backPlane, aOutMin, bOutMax,
                backPlane, aOutMin, bOutMin,
                frontPlane, aOutMin, bOutMin,
                -AxisDirection(a));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMax, bOutMin,
                backPlane, aOutMax, bOutMin,
                backPlane, aOutMax, bOutMax,
                frontPlane, aOutMax, bOutMax,
                AxisDirection(a));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMin, bOutMin,
                backPlane, aOutMin, bOutMin,
                backPlane, aOutMax, bOutMin,
                frontPlane, aOutMax, bOutMin,
                -AxisDirection(b));
            AppendPatchQuad(
                vertices, normals, uvs, triangles, hole, boxMin, boxSize,
                frontPlane, aOutMax, bOutMax,
                backPlane, aOutMax, bOutMax,
                backPlane, aOutMin, bOutMax,
                frontPlane, aOutMin, bOutMax,
                AxisDirection(b));
        }

        if (triangles.Count == 0)
            return false;

        mesh = new Mesh
        {
            name = "PortalSolidRecessPatch"
        };
        mesh.SetVertices(vertices);
        mesh.SetNormals(normals);
        mesh.SetUVs(0, uvs);
        mesh.SetTriangles(triangles, 0);
        mesh.RecalculateBounds();
        return true;
    }

    private static void AppendPatchQuad(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        PortalHole hole,
        Vector3 boxMin,
        Vector3 boxSize,
        float axis0, float a0, float b0,
        float axis1, float a1, float b1,
        float axis2, float a2, float b2,
        float axis3, float a3, float b3,
        Vector3 normal)
    {
        AppendHoleQuad(
            vertices, normals, uvs, triangles,
            HoleCapPoint(hole, axis0, a0, b0),
            HoleCapPoint(hole, axis1, a1, b1),
            HoleCapPoint(hole, axis2, a2, b2),
            HoleCapPoint(hole, axis3, a3, b3),
            normal, boxMin, boxSize);
    }

    private static bool TryGetPortalHoleBounds(
        Portal portal,
        Transform wallTransform,
        Vector3 boxMin,
        Vector3 boxMax,
        out PortalHole hole)
    {
        hole = new PortalHole
        {
            Owner = portal,
            Axis = 0,
            A = 1,
            B = 2,
            Min = Vector3.zero,
            Max = Vector3.zero,
            BackAxis = 0f,
            BackNormalSign = 1f
        };

        Vector3 forwardLocal =
            wallTransform.InverseTransformDirection(portal.transform.forward);
        int axis = 0;
        if (Mathf.Abs(forwardLocal.y) > Mathf.Abs(forwardLocal[axis]))
            axis = 1;
        if (Mathf.Abs(forwardLocal.z) > Mathf.Abs(forwardLocal[axis]))
            axis = 2;
        if (Mathf.Abs(forwardLocal[axis]) < 0.9f)
            return false;

        int a = axis == 0 ? 1 : 0;
        int b = axis == 2 ? 1 : 2;
        if (axis == 1)
            b = 2;

        Vector3 halfWorld = portal.GetPortalHalfSizeWorld();
        // Source cuts the wall brush with 0.1 HU hole modifier plus 0.1 HU
        // minimum wall thickness. Only the lower edge gets the 0.65 HU AABB
        // angle-transform allowance.
        float carve = SourceHoleCarveHu * 2f /
            PortalTransformMath.HammerUnitsPerUnityUnit;
        float halfWidth = halfWorld.x + carve;
        float topExtent = halfWorld.y + carve;
        float bottomExtent = halfWorld.y + carve + SourcePortalBottomCarve;

        Vector3 center = portal.transform.position;
        Vector3 right = portal.transform.right;
        Vector3 up = portal.transform.up;
        float minA = float.PositiveInfinity;
        float maxA = float.NegativeInfinity;
        float minB = float.PositiveInfinity;
        float maxB = float.NegativeInfinity;

        for (int sx = -1; sx <= 1; sx += 2)
        {
            for (int sy = -1; sy <= 1; sy += 2)
            {
                float vertical = sy > 0 ? topExtent : bottomExtent;
                Vector3 corner = center +
                    right * (halfWidth * sx) +
                    up * (vertical * sy);
                Vector3 local = wallTransform.InverseTransformPoint(corner);
                minA = Mathf.Min(minA, local[a]);
                maxA = Mathf.Max(maxA, local[a]);
                minB = Mathf.Min(minB, local[b]);
                maxB = Mathf.Max(maxB, local[b]);
            }
        }

        const float epsilon = 0.00001f;
        Vector3 min = boxMin - Vector3.one * epsilon;
        Vector3 max = boxMax + Vector3.one * epsilon;
        min[a] = Mathf.Clamp(minA, boxMin[a] - epsilon, boxMax[a] + epsilon);
        max[a] = Mathf.Clamp(maxA, boxMin[a] - epsilon, boxMax[a] + epsilon);
        min[b] = Mathf.Clamp(minB, boxMin[b] - epsilon, boxMax[b] + epsilon);
        max[b] = Mathf.Clamp(maxB, boxMin[b] - epsilon, boxMax[b] + epsilon);

        float planeNormalAxis = Vector3.Dot(
            wallTransform.InverseTransformDirection(
                GetPortalPlaneNormal(portal)),
            AxisDirection(axis));
        float frontSign = planeNormalAxis >= 0f ? 1f : -1f;
        float frontFace = frontSign > 0f ? boxMax[axis] : boxMin[axis];

        // Source teleports when the hull centre crosses the portal plane on
        // the traversable face; it never travels through the wall thickness.
        // The recess therefore only has to be deep enough for the hull to get
        // its centre there, and that depth depends on the portal orientation:
        // 16 HU on a wall, up to 36 HU on a floor. It is never clamped to the
        // host wall thickness - RebuildCarvedWall thickens the host instead,
        // so the opposite face always keeps a solid backing plate.
        float worldRecessDepth = GetPortalRecessDepthWorld(portal);
        float axisScale = Mathf.Max(
            0.0001f, Mathf.Abs(wallTransform.lossyScale[axis]));
        float localRecessDepth = worldRecessDepth / axisScale;
        // A floor or ceiling portal is carved straight through instead of
        // getting a recess. The hull has to sink its whole standing
        // half-height (36 HU) past the plane, so the recess can only ever be
        // a few HU deeper than that - and a recess that shallow turns the
        // portal into a pit the player lands in. The crossing then happens on
        // the very command that reaches the recess floor, leaving no travel
        // for the trigger, and every later command reports zero distance as
        // well, so the teleport never fires and the player is left standing
        // inside the floor. A through-hole lets the hull fall freely, so the
        // centre crosses while it is still moving. It also keeps a crouched
        // hull working: the duck half-height is 27 HU, so a duck hull resting
        // on a 40 HU recess floor stops with its centre 12 HU short of the
        // plane and could never teleport at all.
        bool horizontal = IsHorizontalPortal(portal);
        if (horizontal)
        {
            min[axis] = boxMin[axis] - epsilon;
            max[axis] = boxMax[axis] + epsilon;
        }
        else if (frontSign > 0f)
        {
            min[axis] = frontFace - localRecessDepth;
            max[axis] = frontFace + epsilon;
        }
        else
        {
            min[axis] = frontFace - epsilon;
            max[axis] = frontFace + localRecessDepth;
        }

        hole = new PortalHole
        {
            Owner = portal,
            Axis = axis,
            A = a,
            B = b,
            Min = min,
            Max = max,
            BackAxis = frontFace,
            BackNormalSign = frontSign,
            Through = horizontal
        };
        return (max[a] - min[a]) > epsilon &&
               (max[b] - min[b]) > epsilon;
    }

    /// <summary>
    /// Depth the blind recess needs so the hull centre can actually reach the
    /// portal plane from the traversable face, plus the portal's own half
    /// depth and Source's bump forgiveness.
    /// </summary>
    /// <remarks>
    /// The hull is axis aligned and the movement direction that matters is the
    /// plane normal, so the distance it must travel past the face is its
    /// support distance along that normal: the half-depth on a wall (16 HU,
    /// which is exactly the old fixed value, so walls are unchanged), the
    /// half-height on a floor (36 HU), and a blend of both on a slope.
    /// A fixed 20 HU recess can only ever serve a wall. On a 52 degree slope
    /// the hull needs about 35 HU, so it bottomed out on the recess floor with
    /// its centre still 0.28 UU in front of the plane and the portal could
    /// never fire - which is why slopes steeper than 45 degrees were dead
    /// while walls and floors worked.
    ///
    /// Only the depth changes here. The recess still stops short of the
    /// opposite face, so the reverse side stays solid and cannot be entered;
    /// the extra depth comes from thickening the host, not from cutting
    /// through it.
    /// </remarks>
    private static float GetPortalRecessDepthWorld(Portal portal)
    {
        return GetPortalRecessDepthWorld(portal, SourcePlayerHalfHeightHu);
    }

    /// <summary>
    /// Same recess depth but measured against a hull of the given half-height,
    /// in Hammer units. The carve always uses the standing hull; the
    /// placement-time back-clearance check can ask for the ducked one on a
    /// shallow surface.
    /// </summary>
    private static float GetPortalRecessDepthWorld(
        Portal portal, float halfHeightHu)
    {
        if (portal == null)
            return SourceBlindRecessDepthHu /
                PortalTransformMath.HammerUnitsPerUnityUnit;

        Vector3 normal = GetPortalPlaneNormal(portal);
        if (normal.sqrMagnitude < 0.000001f)
            return SourceBlindRecessDepthHu /
                PortalTransformMath.HammerUnitsPerUnityUnit;
        normal.Normalize();

        float sinkHu =
            Mathf.Abs(normal.x) * SourcePlayerHalfWidthHu +
            Mathf.Abs(normal.y) * halfHeightHu +
            Mathf.Abs(normal.z) * SourcePlayerHalfDepthHu;
        float recessHu = sinkHu +
            SourcePortalHalfDepthHu + SourcePortalBumpForgivenessHu;
        return recessHu / PortalTransformMath.HammerUnitsPerUnityUnit;
    }

    /// <summary>
    /// True when the portal plane is horizontal in world space, i.e. the
    /// portal lies on a floor or a ceiling. Those portals are carved straight
    /// through: a hull entering one has to move its whole standing half-height
    /// past the plane, which a blind recess can never allow.
    /// </summary>
    private static bool IsHorizontalPortal(Portal portal)
    {
        if (portal == null)
            return false;

        Vector3 normal = GetPortalPlaneNormal(portal);
        return normal.sqrMagnitude > 0.000001f &&
            Mathf.Abs(Vector3.Dot(
                normal.normalized, Vector3.up)) > 0.7f;
    }

    // ---------------------------------------------------------------------
    // Portal-aligned hole carving.
    //
    // The hole is the rectangular prism swept by the portal quad: right and
    // up come from the portal transform, depth from the portal normal. It is
    // defined in world space and subtracted from the host collider by plane
    // clipping, so a tilted wall or a rotated portal produces exactly the
    // same hole as an axis-aligned one. The previous wall-local AABB only
    // worked while the portal happened to line up with two host axes: on a
    // tilted wall it grew by (|sin|+|cos|) and opened solid wall next to the
    // visible portal.
    // ---------------------------------------------------------------------
    private struct PortalHoleWorld
    {
        public Portal Owner;
        public Vector3 Origin;
        public Vector3 Right;
        public Vector3 Up;
        public Vector3 Normal;
        public float RightExtent;
        public float TopExtent;
        public float BottomExtent;
        public float Front;
        public float Back;
        public bool Through;
    }

    private struct CarveTriangle
    {
        public Vector3 A;
        public Vector3 B;
        public Vector3 C;
        public Vector3 Normal;
        // Caps belong to one opening. While merging overlapping openings,
        // keep that opening's own boundary and clip only against the others.
        public Portal Owner;
    }

    private static bool TryGetWorldHole(
        Portal portal,
        Transform wallTransform,
        Vector3 boxMin,
        Vector3 boxMax,
        out PortalHoleWorld hole)
    {
        hole = default;
        if (portal == null || portal.transform == null ||
            wallTransform == null)
            return false;

        Vector3 normal = GetPortalPlaneNormal(portal);
        Vector3 right = portal.transform.right;
        Vector3 up = portal.transform.up;
        if (normal.sqrMagnitude < 0.5f || right.sqrMagnitude < 0.5f ||
            up.sqrMagnitude < 0.5f)
            return false;
        normal.Normalize();
        right.Normalize();
        up.Normalize();

        Vector3 halfSize = portal.GetPortalHalfSizeWorld();
        float carve = SourceHoleCarveHu * 2f /
            PortalTransformMath.HammerUnitsPerUnityUnit;
        float rightExtent = halfSize.x + carve;
        float topExtent = halfSize.y + carve;
        // Source's AABB angle-transform allowance only widens the lower edge.
        float bottomExtent = -(halfSize.y + carve + SourcePortalBottomCarve);

        Vector3 origin = portal.transform.position;
        bool through = IsHorizontalPortal(portal);
        float front;
        float back;
        if (through)
        {
            // A floor or ceiling portal needs a genuine through-hole. Span
            // the whole host along the portal normal; a surface-only mesh
            // host collapses to a thin slab that removes just its triangles.
            float minDepth = float.PositiveInfinity;
            float maxDepth = float.NegativeInfinity;
            for (int cx = 0; cx < 2; ++cx)
            {
                for (int cy = 0; cy < 2; ++cy)
                {
                    for (int cz = 0; cz < 2; ++cz)
                    {
                        Vector3 local = new Vector3(
                            cx == 0 ? boxMin.x : boxMax.x,
                            cy == 0 ? boxMin.y : boxMax.y,
                            cz == 0 ? boxMin.z : boxMax.z);
                        float depth = Vector3.Dot(
                            wallTransform.TransformPoint(local) - origin,
                            normal);
                        minDepth = Mathf.Min(minDepth, depth);
                        maxDepth = Mathf.Max(maxDepth, depth);
                    }
                }
            }
            if (float.IsInfinity(minDepth) || float.IsInfinity(maxDepth))
                return false;
            // End the prism exactly on the host's two faces. Padding it past
            // either face leaves the four side caps floating in open space;
            // the clipping test already counts boundary triangles as inside,
            // so no pad is needed to remove the covered surface.
            front = maxDepth;
            back = minDepth;
            if (front - back < 0.001f)
            {
                front = 0.001f;
                back = -0.001f;
            }
        }
        else
        {
            // The portal sits on the traversable face, so the recess starts
            // exactly there. A positive pad made the side caps stick out.
            front = 0f;
            back = -GetPortalRecessDepthWorld(portal);
        }

        hole = new PortalHoleWorld
        {
            Owner = portal,
            Origin = origin,
            Right = right,
            Up = up,
            Normal = normal,
            RightExtent = rightExtent,
            TopExtent = topExtent,
            BottomExtent = bottomExtent,
            Front = front,
            Back = back,
            Through = through
        };
        return true;
    }

    private static Vector3 HoleWorldPoint(
        PortalHoleWorld hole, float right, float up, float depth)
    {
        return hole.Origin + hole.Right * right + hole.Up * up +
            hole.Normal * depth;
    }

    private static List<Vector3> ClipPolygonToPlaneWorld(
        List<Vector3> polygon,
        Vector3 planePoint,
        Vector3 planeNormal,
        bool keepPositive)
    {
        List<Vector3> output = new List<Vector3>();
        if (polygon == null || polygon.Count < 3)
            return output;

        const float epsilon = 0.000001f;
        for (int i = 0; i < polygon.Count; ++i)
        {
            Vector3 current = polygon[i];
            Vector3 next = polygon[(i + 1) % polygon.Count];
            float currentDistance = Vector3.Dot(
                current - planePoint, planeNormal);
            float nextDistance = Vector3.Dot(next - planePoint, planeNormal);
            if (!keepPositive)
            {
                currentDistance = -currentDistance;
                nextDistance = -nextDistance;
            }
            bool currentInside = currentDistance >= -epsilon;
            bool nextInside = nextDistance >= -epsilon;
            if (currentInside)
                output.Add(current);
            if (currentInside != nextInside)
            {
                float denominator = currentDistance - nextDistance;
                float t = Mathf.Abs(denominator) > epsilon
                    ? currentDistance / denominator
                    : 0f;
                output.Add(Vector3.Lerp(current, next, t));
            }
        }
        return output;
    }

    private static List<CarveTriangle> CarveTrianglesWorld(
        List<CarveTriangle> source,
        List<PortalHoleWorld> holes)
    {
        List<CarveTriangle> result = new List<CarveTriangle>();
        if (source == null || holes == null)
            return result;

        for (int s = 0; s < source.Count; ++s)
        {
            CarveTriangle triangle = source[s];
            List<List<Vector3>> pieces = new List<List<Vector3>>
            {
                new List<Vector3> { triangle.A, triangle.B, triangle.C }
            };

            for (int h = 0; h < holes.Count && pieces.Count > 0; ++h)
            {
                PortalHoleWorld hole = holes[h];
                if (triangle.Owner != null && triangle.Owner == hole.Owner)
                    continue;
                Vector3[] planePoints =
                {
                    HoleWorldPoint(hole, hole.RightExtent, 0f, 0f),
                    HoleWorldPoint(hole, -hole.RightExtent, 0f, 0f),
                    HoleWorldPoint(hole, 0f, hole.TopExtent, 0f),
                    HoleWorldPoint(hole, 0f, hole.BottomExtent, 0f),
                    HoleWorldPoint(hole, 0f, 0f, hole.Front),
                    HoleWorldPoint(hole, 0f, 0f, hole.Back)
                };
                Vector3[] outward =
                {
                    hole.Right, -hole.Right, hole.Up, -hole.Up,
                    hole.Normal, -hole.Normal
                };

                List<List<Vector3>> surviving = new List<List<Vector3>>();
                for (int p = 0; p < pieces.Count; ++p)
                {
                    List<List<Vector3>> outside = new List<List<Vector3>>();
                    List<List<Vector3>> pending = new List<List<Vector3>>
                    {
                        pieces[p]
                    };
                    for (int plane = 0;
                         plane < outward.Length && pending.Count > 0;
                         ++plane)
                    {
                        List<List<Vector3>> stillInside =
                            new List<List<Vector3>>();
                        for (int q = 0; q < pending.Count; ++q)
                        {
                            bool coplanar = true;
                            for (int v = 0; v < pending[q].Count; ++v)
                            {
                                if (Mathf.Abs(Vector3.Dot(
                                        pending[q][v] - planePoints[plane],
                                        outward[plane])) > 0.000001f)
                                {
                                    coplanar = false;
                                    break;
                                }
                            }
                            if (coplanar)
                            {
                                // A source surface on the carve boundary is
                                // removed with the opening instead of becoming
                                // a false floor at the edge of a through-hole.
                                stillInside.Add(pending[q]);
                                continue;
                            }
                            List<Vector3> outsidePart =
                                ClipPolygonToPlaneWorld(
                                    pending[q], planePoints[plane],
                                    outward[plane], true);
                            List<Vector3> insidePart =
                                ClipPolygonToPlaneWorld(
                                    pending[q], planePoints[plane],
                                    outward[plane], false);
                            if (outsidePart.Count >= 3)
                                outside.Add(outsidePart);
                            if (insidePart.Count >= 3)
                                stillInside.Add(insidePart);
                        }
                        pending = stillInside;
                    }
                    // Anything still pending is inside all six faces, i.e.
                    // inside the hole prism, and is discarded.
                    surviving.AddRange(outside);
                }
                pieces = surviving;
            }

            for (int p = 0; p < pieces.Count; ++p)
            {
                List<Vector3> polygon = pieces[p];
                for (int i = 1; i < polygon.Count - 1; ++i)
                {
                    result.Add(new CarveTriangle
                    {
                        A = polygon[0],
                        B = polygon[i],
                        C = polygon[i + 1],
                        Normal = triangle.Normal,
                        Owner = triangle.Owner
                    });
                }
            }
        }
        return result;
    }

    private static void AppendWorldQuad(
        List<CarveTriangle> output,
        Vector3 a,
        Vector3 b,
        Vector3 c,
        Vector3 d,
        Vector3 normal,
        Portal owner)
    {
        if (Vector3.Dot(Vector3.Cross(b - a, c - a), normal) < 0f)
        {
            Vector3 swap = b;
            b = d;
            d = swap;
        }
        output.Add(new CarveTriangle
        {
            A = a, B = b, C = c, Normal = normal, Owner = owner
        });
        output.Add(new CarveTriangle
        {
            A = a, B = c, C = d, Normal = normal, Owner = owner
        });
    }

    private static void AppendWorldHoleCaps(
        List<CarveTriangle> output,
        PortalHoleWorld hole)
    {
        float r = hole.RightExtent;
        float top = hole.TopExtent;
        float bottom = hole.BottomExtent;
        float front = hole.Front;
        float back = hole.Back;

        // Four side walls. Their normals point into the hole, i.e. towards
        // the traversable volume the solid was carved away from.
        AppendWorldQuad(output,
            HoleWorldPoint(hole, r, bottom, front),
            HoleWorldPoint(hole, r, top, front),
            HoleWorldPoint(hole, r, top, back),
            HoleWorldPoint(hole, r, bottom, back), -hole.Right, hole.Owner);
        AppendWorldQuad(output,
            HoleWorldPoint(hole, -r, top, front),
            HoleWorldPoint(hole, -r, bottom, front),
            HoleWorldPoint(hole, -r, bottom, back),
            HoleWorldPoint(hole, -r, top, back), hole.Right, hole.Owner);
        AppendWorldQuad(output,
            HoleWorldPoint(hole, -r, top, front),
            HoleWorldPoint(hole, r, top, front),
            HoleWorldPoint(hole, r, top, back),
            HoleWorldPoint(hole, -r, top, back), -hole.Up, hole.Owner);
        AppendWorldQuad(output,
            HoleWorldPoint(hole, r, bottom, front),
            HoleWorldPoint(hole, -r, bottom, front),
            HoleWorldPoint(hole, -r, bottom, back),
            HoleWorldPoint(hole, r, bottom, back), hole.Up, hole.Owner);

        // The recess is blind, so it needs its own bottom cap. This is what
        // the hull actually stands on inside the recess, and it sits deep
        // enough (support distance + forgiveness) that the centre still ends
        // up past the portal plane.
        if (!hole.Through)
        {
            AppendWorldQuad(output,
                HoleWorldPoint(hole, -r, bottom, back),
                HoleWorldPoint(hole, r, bottom, back),
                HoleWorldPoint(hole, r, top, back),
                HoleWorldPoint(hole, -r, top, back), hole.Normal,
                hole.Owner);
        }
    }

    private static bool TryBuildWorldHoleUnionCaps(
        List<PortalHoleWorld> worldHoles,
        out List<CarveTriangle> worldCaps)
    {
        worldCaps = new List<CarveTriangle>();
        if (worldHoles == null || worldHoles.Count == 0)
            return false;

        PortalHoleWorld first = worldHoles[0];
        Vector3 basisOrigin = first.Origin;
        Vector3 basisRight = first.Right.normalized;
        Vector3 basisUp = first.Up.normalized;
        Vector3 basisNormal = first.Normal.normalized;
        const float alignmentTolerance = 0.999f;
        if (Mathf.Abs(Vector3.Dot(basisRight, basisUp)) > 0.001f ||
            Mathf.Abs(Vector3.Dot(basisRight, basisNormal)) > 0.001f ||
            Mathf.Abs(Vector3.Dot(basisUp, basisNormal)) > 0.001f)
            return false;

        List<PortalHole> localHoles = new List<PortalHole>(worldHoles.Count);
        for (int h = 0; h < worldHoles.Count; ++h)
        {
            PortalHoleWorld source = worldHoles[h];
            Vector3 sourceRight = source.Right.normalized;
            Vector3 sourceUp = source.Up.normalized;
            Vector3 sourceNormal = source.Normal.normalized;
            if (Mathf.Abs(Vector3.Dot(basisRight, sourceRight)) <
                    alignmentTolerance ||
                Mathf.Abs(Vector3.Dot(basisUp, sourceUp)) <
                    alignmentTolerance ||
                Mathf.Abs(Vector3.Dot(basisNormal, sourceNormal)) <
                    alignmentTolerance)
                return false;

            Vector3 min = new Vector3(
                float.PositiveInfinity, float.PositiveInfinity,
                float.PositiveInfinity);
            Vector3 max = new Vector3(
                float.NegativeInfinity, float.NegativeInfinity,
                float.NegativeInfinity);
            float[] rightValues =
                { -source.RightExtent, source.RightExtent };
            float[] upValues =
                { source.BottomExtent, source.TopExtent };
            float[] depthValues = { source.Front, source.Back };
            for (int r = 0; r < rightValues.Length; ++r)
            {
                for (int u = 0; u < upValues.Length; ++u)
                {
                    for (int d = 0; d < depthValues.Length; ++d)
                    {
                        Vector3 point = HoleWorldPoint(
                            source, rightValues[r], upValues[u],
                            depthValues[d]);
                        Vector3 relative = point - basisOrigin;
                        Vector3 local = new Vector3(
                            Vector3.Dot(relative, basisRight),
                            Vector3.Dot(relative, basisUp),
                            Vector3.Dot(relative, basisNormal));
                        min = Vector3.Min(min, local);
                        max = Vector3.Max(max, local);
                    }
                }
            }

            localHoles.Add(new PortalHole
            {
                Owner = source.Owner,
                Axis = 2,
                A = 0,
                B = 1,
                Min = min,
                Max = max,
                BackAxis = Vector3.Dot(
                    source.Origin - basisOrigin, basisNormal),
                BackNormalSign = Vector3.Dot(
                    sourceNormal, basisNormal) >= 0f ? 1f : -1f,
                Through = source.Through
            });
        }

        List<CarveTriangle> localCaps = BuildLocalHoleUnionCaps(localHoles);
        for (int i = 0; i < localCaps.Count; ++i)
        {
            CarveTriangle cap = localCaps[i];
            worldCaps.Add(new CarveTriangle
            {
                A = basisOrigin + basisRight * cap.A.x +
                    basisUp * cap.A.y + basisNormal * cap.A.z,
                B = basisOrigin + basisRight * cap.B.x +
                    basisUp * cap.B.y + basisNormal * cap.B.z,
                C = basisOrigin + basisRight * cap.C.x +
                    basisUp * cap.C.y + basisNormal * cap.C.z,
                Normal = (basisRight * cap.Normal.x +
                    basisUp * cap.Normal.y +
                    basisNormal * cap.Normal.z).normalized
            });
        }
        return true;
    }

    private static bool BuildWorldCarvedMesh(
        Vector3 boxMin,
        Vector3 boxMax,
        Mesh sourceMesh,
        List<PortalHoleWorld> holes,
        Transform wallTransform,
        out Mesh mesh)
    {
        mesh = null;
        if (holes == null || holes.Count == 0 || wallTransform == null)
            return false;

        List<CarveTriangle> source = new List<CarveTriangle>();
        if (sourceMesh != null)
        {
            if (!sourceMesh.isReadable)
                return false;
            Vector3[] localVertices = sourceMesh.vertices;
            int[] indices = sourceMesh.triangles;
            if (localVertices == null || indices == null || indices.Length < 3)
                return false;
            for (int i = 0; i + 2 < indices.Length; i += 3)
            {
                int i0 = indices[i];
                int i1 = indices[i + 1];
                int i2 = indices[i + 2];
                if (i0 >= localVertices.Length || i1 >= localVertices.Length ||
                    i2 >= localVertices.Length)
                    continue;
                Vector3 a = wallTransform.TransformPoint(localVertices[i0]);
                Vector3 b = wallTransform.TransformPoint(localVertices[i1]);
                Vector3 c = wallTransform.TransformPoint(localVertices[i2]);
                Vector3 faceNormal = Vector3.Cross(b - a, c - a);
                if (faceNormal.sqrMagnitude <= 0.000001f)
                    continue;
                source.Add(new CarveTriangle
                {
                    A = a, B = b, C = c, Normal = faceNormal.normalized
                });
            }
        }
        else
        {
            Vector3[] local =
            {
                new Vector3(boxMin.x, boxMin.y, boxMin.z),
                new Vector3(boxMax.x, boxMin.y, boxMin.z),
                new Vector3(boxMax.x, boxMax.y, boxMin.z),
                new Vector3(boxMin.x, boxMax.y, boxMin.z),
                new Vector3(boxMin.x, boxMin.y, boxMax.z),
                new Vector3(boxMax.x, boxMin.y, boxMax.z),
                new Vector3(boxMax.x, boxMax.y, boxMax.z),
                new Vector3(boxMin.x, boxMax.y, boxMax.z)
            };
            Vector3[] world = new Vector3[local.Length];
            for (int i = 0; i < local.Length; ++i)
                world[i] = wallTransform.TransformPoint(local[i]);
            int[][] faces =
            {
                new[] { 0, 1, 2, 3 }, new[] { 5, 4, 7, 6 },
                new[] { 4, 0, 3, 7 }, new[] { 1, 5, 6, 2 },
                new[] { 4, 5, 1, 0 }, new[] { 3, 2, 6, 7 }
            };
            Vector3 boxCenterWorld = wallTransform.TransformPoint(
                (boxMin + boxMax) * 0.5f);
            for (int f = 0; f < faces.Length; ++f)
            {
                int[] face = (int[])faces[f].Clone();
                Vector3 faceNormal = Vector3.Cross(
                    world[face[1]] - world[face[0]],
                    world[face[2]] - world[face[0]]);
                if (faceNormal.sqrMagnitude <= 0.000001f)
                    continue;
                // A MeshCollider is one-sided for sweeps. The box faces must
                // face OUT of the solid or Physics.BoxCast sees no wall at
                // all and the hull falls straight through the floor.
                Vector3 faceCenter = (world[face[0]] + world[face[1]] +
                    world[face[2]] + world[face[3]]) * 0.25f;
                if (Vector3.Dot(faceNormal, faceCenter - boxCenterWorld) < 0f)
                {
                    int swap = face[1];
                    face[1] = face[3];
                    face[3] = swap;
                    faceNormal = -faceNormal;
                }
                faceNormal.Normalize();
                source.Add(new CarveTriangle
                {
                    A = world[face[0]], B = world[face[1]],
                    C = world[face[2]], Normal = faceNormal
                });
                source.Add(new CarveTriangle
                {
                    A = world[face[0]], B = world[face[2]],
                    C = world[face[3]], Normal = faceNormal
                });
            }
        }

        List<CarveTriangle> carved = CarveTrianglesWorld(source, holes);
        List<CarveTriangle> unionCaps;
        if (TryBuildWorldHoleUnionCaps(holes, out unionCaps))
        {
            carved.AddRange(unionCaps);
        }
        else
        {
            // Non-parallel openings cannot use the axis grid. Keep the
            // portal-aligned clipping path for those uncommon intersections.
            for (int h = 0; h < holes.Count; ++h)
            {
                List<CarveTriangle> caps = new List<CarveTriangle>(10);
                AppendWorldHoleCaps(caps, holes[h]);
                carved.AddRange(CarveTrianglesWorld(caps, holes));
            }
        }
        if (carved.Count == 0)
            return false;

        List<Vector3> vertices = new List<Vector3>(carved.Count * 3);
        List<Vector3> normals = new List<Vector3>(carved.Count * 3);
        List<int> triangles = new List<int>(carved.Count * 3);
        for (int i = 0; i < carved.Count; ++i)
        {
            CarveTriangle t = carved[i];
            Vector3 normal = t.Normal;
            Vector3 cross = Vector3.Cross(t.B - t.A, t.C - t.A);
            if (cross.sqrMagnitude > 0.000001f && Vector3.Dot(cross, normal) < 0f)
            {
                Vector3 swap = t.B;
                t.B = t.C;
                t.C = swap;
            }
            int start = vertices.Count;
            vertices.Add(wallTransform.InverseTransformPoint(t.A));
            vertices.Add(wallTransform.InverseTransformPoint(t.B));
            vertices.Add(wallTransform.InverseTransformPoint(t.C));
            normals.Add(normal);
            normals.Add(normal);
            normals.Add(normal);
            triangles.Add(start);
            triangles.Add(start + 1);
            triangles.Add(start + 2);
        }

        mesh = new Mesh();
        mesh.name = "PortalCarvedWall";
        mesh.hideFlags = HideFlags.HideAndDontSave;
        mesh.SetVertices(vertices);
        mesh.SetNormals(normals);
        mesh.SetTriangles(triangles, 0);
        mesh.RecalculateBounds();
        return true;
    }

    private static bool BuildBoxCarvedWallMesh(
        Vector3 boxMin,
        Vector3 boxMax,
        List<PortalHole> holes,
        List<BackCapRange> backCaps,
        out Mesh mesh)
    {
        mesh = null;
        List<float>[] cuts =
        {
            new List<float> { boxMin.x, boxMax.x },
            new List<float> { boxMin.y, boxMax.y },
            new List<float> { boxMin.z, boxMax.z }
        };

        const float epsilon = 0.00001f;
        for (int i = 0; i < holes.Count; ++i)
        {
            Vector3 holeMin = holes[i].Min;
            Vector3 holeMax = holes[i].Max;
            for (int axis = 0; axis < 3; ++axis)
            {
                if (Mathf.Abs(holeMin[axis] - boxMin[axis]) <= epsilon &&
                    Mathf.Abs(holeMax[axis] - boxMax[axis]) <= epsilon)
                    continue;
                cuts[axis].Add(Mathf.Clamp(
                    holeMin[axis], boxMin[axis], boxMax[axis]));
                cuts[axis].Add(Mathf.Clamp(
                    holeMax[axis], boxMin[axis], boxMax[axis]));
            }
        }

        for (int axis = 0; axis < 3; ++axis)
        {
            cuts[axis].Sort();
            for (int i = cuts[axis].Count - 1; i > 0; --i)
            {
                if (cuts[axis][i] - cuts[axis][i - 1] <= epsilon)
                    cuts[axis].RemoveAt(i);
            }
        }

        int nx = cuts[0].Count - 1;
        int ny = cuts[1].Count - 1;
        int nz = cuts[2].Count - 1;
        bool[,,] solid = new bool[nx, ny, nz];
        for (int ix = 0; ix < nx; ++ix)
        {
            for (int iy = 0; iy < ny; ++iy)
            {
                for (int iz = 0; iz < nz; ++iz)
                {
                    Vector3 cellMin = new Vector3(
                        cuts[0][ix], cuts[1][iy], cuts[2][iz]);
                    Vector3 cellMax = new Vector3(
                        cuts[0][ix + 1], cuts[1][iy + 1], cuts[2][iz + 1]);
                    Vector3 cellCenter = (cellMin + cellMax) * 0.5f;

                    bool insideHole = false;
                    for (int i = 0; i < holes.Count; ++i)
                    {
                        Vector3 holeMin = holes[i].Min;
                        Vector3 holeMax = holes[i].Max;
                        if (cellCenter.x > holeMin.x + epsilon &&
                            cellCenter.x < holeMax.x - epsilon &&
                            cellCenter.y > holeMin.y + epsilon &&
                            cellCenter.y < holeMax.y - epsilon &&
                            cellCenter.z > holeMin.z + epsilon &&
                            cellCenter.z < holeMax.z - epsilon)
                        {
                            insideHole = true;
                            break;
                        }
                    }
                    solid[ix, iy, iz] = !insideHole;
                }
            }
        }

        List<Vector3> vertices = new List<Vector3>();
        List<Vector3> normals = new List<Vector3>();
        List<Vector2> uvs = new List<Vector2>();
        List<int> triangles = new List<int>();
        Vector3 boxSize = boxMax - boxMin;
        for (int ix = 0; ix < nx; ++ix)
        {
            for (int iy = 0; iy < ny; ++iy)
            {
                for (int iz = 0; iz < nz; ++iz)
                {
                    if (!solid[ix, iy, iz])
                        continue;

                    Vector3 cmin = new Vector3(
                        cuts[0][ix], cuts[1][iy], cuts[2][iz]);
                    Vector3 cmax = new Vector3(
                        cuts[0][ix + 1], cuts[1][iy + 1], cuts[2][iz + 1]);
                    Vector3 p0 = new Vector3(cmin.x, cmin.y, cmin.z);
                    Vector3 p1 = new Vector3(cmax.x, cmin.y, cmin.z);
                    Vector3 p2 = new Vector3(cmax.x, cmax.y, cmin.z);
                    Vector3 p3 = new Vector3(cmin.x, cmax.y, cmin.z);
                    Vector3 p4 = new Vector3(cmin.x, cmin.y, cmax.z);
                    Vector3 p5 = new Vector3(cmax.x, cmin.y, cmax.z);
                    Vector3 p6 = new Vector3(cmax.x, cmax.y, cmax.z);
                    Vector3 p7 = new Vector3(cmin.x, cmax.y, cmax.z);

                    // Only emit faces exposed by the outside of the wall or
                    // by a removed hole cell. Internal cell faces would make
                    // the renderer show seams and fake wall interiors.
                    if (ix == 0 || !solid[ix - 1, iy, iz])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p0, p4, p7, p3, Vector3.left, boxMin, boxSize);
                    if (ix == nx - 1 || !solid[ix + 1, iy, iz])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p1, p2, p6, p5, Vector3.right, boxMin, boxSize);
                    if (iy == 0 || !solid[ix, iy - 1, iz])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p0, p1, p5, p4, Vector3.down, boxMin, boxSize);
                    if (iy == ny - 1 || !solid[ix, iy + 1, iz])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p3, p7, p6, p2, Vector3.up, boxMin, boxSize);
                    if (iz == 0 || !solid[ix, iy, iz - 1])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p0, p3, p2, p1, Vector3.back, boxMin, boxSize);
                    if (iz == nz - 1 || !solid[ix, iy, iz + 1])
                        AppendCarvedFace(vertices, normals, uvs, triangles,
                            p4, p5, p6, p7, Vector3.forward, boxMin, boxSize);
                }
            }
        }

        // No back cap: the carve is now a blind recess from the traversable
        // face. The untouched opposite wall face is the reverse-side blocker.
        if (triangles.Count == 0)
            return false;

        mesh = new Mesh();
        mesh.name = "PortalCarvedWall";
        mesh.hideFlags = HideFlags.HideAndDontSave;
        mesh.SetVertices(vertices);
        mesh.SetNormals(normals);
        mesh.SetUVs(0, uvs);
        mesh.SetTriangles(triangles, 0);
        mesh.RecalculateBounds();
        return true;
    }

    private static Vector2 CarvedUv(
        Vector3 point,
        Vector3 normal,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        if (Mathf.Abs(normal.x) > 0.5f)
            return new Vector2(
                (point.z - boxMin.z) / Mathf.Max(0.000001f, boxSize.z),
                (point.y - boxMin.y) / Mathf.Max(0.000001f, boxSize.y));
        if (Mathf.Abs(normal.y) > 0.5f)
            return new Vector2(
                (point.x - boxMin.x) / Mathf.Max(0.000001f, boxSize.x),
                (point.z - boxMin.z) / Mathf.Max(0.000001f, boxSize.z));
        return new Vector2(
            (point.x - boxMin.x) / Mathf.Max(0.000001f, boxSize.x),
            (point.y - boxMin.y) / Mathf.Max(0.000001f, boxSize.y));
    }

    private static void AppendCarvedFace(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        Vector3 a,
        Vector3 b,
        Vector3 c,
        Vector3 d,
        Vector3 normal,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        int start = vertices.Count;
        vertices.Add(a);
        vertices.Add(b);
        vertices.Add(c);
        vertices.Add(d);
        normals.Add(normal);
        normals.Add(normal);
        normals.Add(normal);
        normals.Add(normal);
        uvs.Add(CarvedUv(a, normal, boxMin, boxSize));
        uvs.Add(CarvedUv(b, normal, boxMin, boxSize));
        uvs.Add(CarvedUv(c, normal, boxMin, boxSize));
        uvs.Add(CarvedUv(d, normal, boxMin, boxSize));
        triangles.Add(start);
        triangles.Add(start + 1);
        triangles.Add(start + 2);
        triangles.Add(start);
        triangles.Add(start + 2);
        triangles.Add(start + 3);
    }

    private static bool BuildMeshCarvedWallMesh(
        Mesh sourceMesh,
        Vector3 boxMin,
        Vector3 boxMax,
        List<PortalHole> holes,
        List<BackCapRange> backCaps,
        out Mesh mesh)
    {
        mesh = null;
        if (sourceMesh == null || holes == null || holes.Count == 0)
            return false;

        // Clipping needs the triangle data. A mesh imported without Read/Write
        // enabled cannot be carved, so fall back to the aperture filter rather
        // than throwing inside the placement path.
        if (!sourceMesh.isReadable)
            return false;

        Vector3[] sourceVertices = sourceMesh.vertices;
        int[] sourceTriangles = sourceMesh.triangles;
        if (sourceVertices == null || sourceTriangles == null ||
            sourceTriangles.Length < 3)
            return false;

        const float epsilon = 0.00001f;
        Vector3 boxSize = boxMax - boxMin;
        List<Vector3> vertices = new List<Vector3>();
        List<Vector3> normals = new List<Vector3>();
        List<Vector2> uvs = new List<Vector2>();
        List<int> triangles = new List<int>();

        // Remove the blind-recess volume from each source triangle. Unlike the
        // box host, a mesh host is a surface with no volume to carve, so the
        // recess is cut as a real pocket: only triangles inside the pocket box
        // (hole rectangle x recess depth) are removed. A closed mesh keeps its
        // opposite face because that face lies beyond the recess depth, which
        // is what makes the reverse side stay solid.
        for (int t = 0; t < sourceTriangles.Length; t += 3)
        {
            int i0 = sourceTriangles[t];
            int i1 = sourceTriangles[t + 1];
            int i2 = sourceTriangles[t + 2];
            if (i0 >= sourceVertices.Length || i1 >= sourceVertices.Length ||
                i2 >= sourceVertices.Length)
                continue;

            Vector3 faceNormal = Vector3.Cross(
                sourceVertices[i1] - sourceVertices[i0],
                sourceVertices[i2] - sourceVertices[i0]);
            if (faceNormal.sqrMagnitude <= epsilon)
                continue;
            faceNormal.Normalize();

            List<List<Vector3>> pieces = new List<List<Vector3>>
            {
                new List<Vector3>
                {
                    sourceVertices[i0],
                    sourceVertices[i1],
                    sourceVertices[i2]
                }
            };

            for (int h = 0; h < holes.Count && pieces.Count > 0; ++h)
            {
                PortalHole hole = holes[h];
                // Six half-planes: the hole rectangle in A/B plus the recess
                // depth along the wall axis. Anything still inside all six is
                // inside the pocket and is discarded.
                int[] coords =
                {
                    hole.A, hole.A, hole.B, hole.B,
                    hole.Axis, hole.Axis
                };
                float[] values =
                {
                    hole.Min[hole.A], hole.Max[hole.A],
                    hole.Min[hole.B], hole.Max[hole.B],
                    hole.Min[hole.Axis], hole.Max[hole.Axis]
                };
                bool[] keepGreater = { false, true, false, true, false, true };
                List<List<Vector3>> nextPieces = new List<List<Vector3>>();

                for (int p = 0; p < pieces.Count; ++p)
                {
                    List<List<Vector3>> pending = new List<List<Vector3>>
                    {
                        pieces[p]
                    };
                    List<List<Vector3>> outsidePieces =
                        new List<List<Vector3>>();

                    for (int plane = 0;
                         plane < coords.Length && pending.Count > 0;
                         ++plane)
                    {
                        List<List<Vector3>> nextPending =
                            new List<List<Vector3>>();
                        for (int q = 0; q < pending.Count; ++q)
                        {
                            bool coplanar = true;
                            for (int v = 0; v < pending[q].Count; ++v)
                            {
                                if (Mathf.Abs(
                                        pending[q][v][coords[plane]] -
                                        values[plane]) > 0.000001f)
                                {
                                    coplanar = false;
                                    break;
                                }
                            }
                            if (coplanar)
                            {
                                // A source face exactly on a carve boundary
                                // belongs to the removed volume. Keeping it
                                // as both inside and outside leaves a false
                                // floor across through-holes.
                                nextPending.Add(pending[q]);
                                continue;
                            }
                            List<Vector3> outside = ClipPolygonToHalfPlane(
                                pending[q], coords[plane], values[plane],
                                keepGreater[plane]);
                            List<Vector3> inside = ClipPolygonToHalfPlane(
                                pending[q], coords[plane], values[plane],
                                !keepGreater[plane]);
                            if (outside.Count >= 3)
                                outsidePieces.Add(outside);
                            if (inside.Count >= 3)
                                nextPending.Add(inside);
                        }
                        pending = nextPending;
                    }
                    nextPieces.AddRange(outsidePieces);
                    // Anything still pending is inside all six half-planes,
                    // i.e. inside the recess pocket, and must be discarded.
                }
                pieces = nextPieces;
            }

            for (int p = 0; p < pieces.Count; ++p)
            {
                AppendCarvedPolygon(
                    vertices, normals, uvs, triangles,
                    pieces[p], faceNormal, boxMin, boxSize);
            }
        }

        // The source surface now has a pocket-shaped gap. Extract the boundary
        // of the union of all opening volumes, so overlap regions contain no
        // internal side walls and shared outer walls are emitted only once.
        List<CarveTriangle> unionCaps = BuildLocalHoleUnionCaps(holes);
        for (int i = 0; i < unionCaps.Count; ++i)
        {
            CarveTriangle cap = unionCaps[i];
            AppendCarvedTriangle(
                vertices, normals, uvs, triangles,
                cap.A, cap.B, cap.C, cap.Normal, boxMin, boxSize);
        }

        // No back cap: the carve is now a blind recess from the traversable
        // face. The untouched opposite wall face is the reverse-side blocker.
        if (triangles.Count == 0)
            return false;

        mesh = new Mesh();
        mesh.name = "PortalCarvedWall";
        mesh.hideFlags = HideFlags.HideAndDontSave;
        mesh.SetVertices(vertices);
        mesh.SetNormals(normals);
        mesh.SetUVs(0, uvs);
        mesh.SetTriangles(triangles, 0);
        mesh.RecalculateBounds();
        return true;
    }

    private static List<Vector3> ClipPolygonToHalfPlane(
        List<Vector3> polygon,
        int coordinate,
        float value,
        bool keepGreater)
    {
        List<Vector3> output = new List<Vector3>();
        if (polygon == null || polygon.Count < 3)
            return output;

        const float epsilon = 0.000001f;
        for (int i = 0; i < polygon.Count; ++i)
        {
            Vector3 current = polygon[i];
            Vector3 next = polygon[(i + 1) % polygon.Count];
            float currentDistance = keepGreater
                ? current[coordinate] - value
                : value - current[coordinate];
            float nextDistance = keepGreater
                ? next[coordinate] - value
                : value - next[coordinate];
            bool currentInside = currentDistance >= -epsilon;
            bool nextInside = nextDistance >= -epsilon;

            if (currentInside)
                output.Add(current);
            if (currentInside != nextInside)
            {
                float denominator = currentDistance - nextDistance;
                float t = Mathf.Abs(denominator) > epsilon
                    ? currentDistance / denominator
                    : 0f;
                output.Add(Vector3.Lerp(current, next, t));
            }
        }
        return output;
    }

    private static void AppendCarvedPolygon(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        List<Vector3> polygon,
        Vector3 normal,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        for (int i = 1; i < polygon.Count - 1; ++i)
        {
            AppendCarvedTriangle(
                vertices, normals, uvs, triangles,
                polygon[0], polygon[i], polygon[i + 1],
                normal, boxMin, boxSize);
        }
    }

    private static void AppendCarvedTriangle(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        Vector3 a,
        Vector3 b,
        Vector3 c,
        Vector3 normal,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        Vector3 faceNormal = Vector3.Cross(b - a, c - a);
        if (Vector3.Dot(faceNormal, normal) < 0f)
        {
            Vector3 swap = b;
            b = c;
            c = swap;
        }

        int start = vertices.Count;
        vertices.Add(a);
        vertices.Add(b);
        vertices.Add(c);
        normals.Add(normal);
        normals.Add(normal);
        normals.Add(normal);
        uvs.Add(CarvedUv(a, normal, boxMin, boxSize));
        uvs.Add(CarvedUv(b, normal, boxMin, boxSize));
        uvs.Add(CarvedUv(c, normal, boxMin, boxSize));
        triangles.Add(start);
        triangles.Add(start + 1);
        triangles.Add(start + 2);
    }

    private static Vector3 HoleCapPoint(
        PortalHole hole,
        float axisValue,
        float aValue,
        float bValue)
    {
        Vector3 point = Vector3.zero;
        point[hole.Axis] = axisValue;
        point[hole.A] = aValue;
        point[hole.B] = bValue;
        return point;
    }

    private static Vector3 AxisDirection(int axis)
    {
        if (axis == 0)
            return Vector3.right;
        if (axis == 1)
            return Vector3.up;
        return Vector3.forward;
    }

    private static void AppendHoleCapA(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        PortalHole hole,
        float axisMin,
        float axisMax,
        float aValue,
        float bMin,
        float bMax,
        bool positiveA,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        Vector3 p0 = HoleCapPoint(hole, axisMin, aValue, bMin);
        Vector3 p1 = HoleCapPoint(hole, axisMax, aValue, bMin);
        Vector3 p2 = HoleCapPoint(hole, axisMax, aValue, bMax);
        Vector3 p3 = HoleCapPoint(hole, axisMin, aValue, bMax);
        Vector3 normal = AxisDirection(hole.A) * (positiveA ? 1f : -1f);
        AppendHoleQuad(vertices, normals, uvs, triangles,
            p0, p1, p2, p3, normal, boxMin, boxSize);
    }

    private static void AppendHoleCapB(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        PortalHole hole,
        float aMin,
        float aMax,
        float axisMin,
        float axisMax,
        float bValue,
        bool positiveB,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        Vector3 p0 = HoleCapPoint(hole, axisMin, aMin, bValue);
        Vector3 p1 = HoleCapPoint(hole, axisMax, aMin, bValue);
        Vector3 p2 = HoleCapPoint(hole, axisMax, aMax, bValue);
        Vector3 p3 = HoleCapPoint(hole, axisMin, aMax, bValue);
        Vector3 normal = AxisDirection(hole.B) * (positiveB ? 1f : -1f);
        AppendHoleQuad(vertices, normals, uvs, triangles,
            p0, p1, p2, p3, normal, boxMin, boxSize);
    }

    private static void AppendHoleFloor(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        PortalHole hole,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        // The floor of the blind recess, facing back toward the traversable
        // face. It is the surface that stops the hull one player half-depth
        // past the portal plane, so a surface-only (polygon) host needs no
        // thickness of its own. The portal plane is on the traversable face,
        // so the floor is on the far side of the recess: the low axis end when
        // the face normal points along +axis, the high end otherwise.
        float axisValue = hole.BackNormalSign > 0f
            ? hole.Min[hole.Axis]
            : hole.Max[hole.Axis];
        Vector3 p0 = HoleCapPoint(
            hole, axisValue, hole.Min[hole.A], hole.Min[hole.B]);
        Vector3 p1 = HoleCapPoint(
            hole, axisValue, hole.Max[hole.A], hole.Min[hole.B]);
        Vector3 p2 = HoleCapPoint(
            hole, axisValue, hole.Max[hole.A], hole.Max[hole.B]);
        Vector3 p3 = HoleCapPoint(
            hole, axisValue, hole.Min[hole.A], hole.Max[hole.B]);
        Vector3 normal = AxisDirection(hole.Axis) * hole.BackNormalSign;
        AppendHoleQuad(vertices, normals, uvs, triangles,
            p0, p1, p2, p3, normal, boxMin, boxSize);
    }

    private static void AppendBackCap(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        PortalHole hole,
        List<BackCapRange> backCaps,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        int start = triangles.Count / 3;
        Vector3 p0 = HoleCapPoint(
            hole, hole.BackAxis, hole.Min[hole.A], hole.Min[hole.B]);
        Vector3 p1 = HoleCapPoint(
            hole, hole.BackAxis, hole.Max[hole.A], hole.Min[hole.B]);
        Vector3 p2 = HoleCapPoint(
            hole, hole.BackAxis, hole.Max[hole.A], hole.Max[hole.B]);
        Vector3 p3 = HoleCapPoint(
            hole, hole.BackAxis, hole.Min[hole.A], hole.Max[hole.B]);
        // PlaneNormal points at the traversable (portal) face, so the cap on
        // the opposite face must point AWAY from the portal, toward the
        // reverse side. Unity's MeshCollider generates contacts one-sided:
        // a face only blocks a hull approaching from its normal side. The old
        // winding pointed into the wall, which is why the reverse side could
        // pass through; adding a second reversed winding on the same plane
        // made it block but created overlapping triangles that catch the hull
        // and stick near the reverse face. One outward-facing winding blocks
        // reverse entry cleanly and leaves the front-to-back crossing open.
        Vector3 normal =
            AxisDirection(hole.Axis) * -hole.BackNormalSign;
        AppendHoleQuad(vertices, normals, uvs, triangles,
            p0, p1, p2, p3, normal, boxMin, boxSize);
        backCaps.Add(new BackCapRange
        {
            Owner = hole.Owner,
            TriangleStart = start,
            TriangleCount = triangles.Count / 3 - start
        });
    }

    private static void AppendHoleQuad(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        List<int> triangles,
        Vector3 a,
        Vector3 b,
        Vector3 c,
        Vector3 d,
        Vector3 normal,
        Vector3 boxMin,
        Vector3 boxSize)
    {
        Vector3 faceNormal = Vector3.Cross(b - a, c - a);
        if (Vector3.Dot(faceNormal, normal) >= 0f)
            AppendCarvedFace(vertices, normals, uvs, triangles,
                a, b, c, d, normal, boxMin, boxSize);
        else
            AppendCarvedFace(vertices, normals, uvs, triangles,
                a, d, c, b, normal, boxMin, boxSize);
    }

    private static List<CarveTriangle> BuildLocalHoleUnionCaps(
        List<PortalHole> holes)
    {
        List<CarveTriangle> caps = new List<CarveTriangle>();
        if (holes == null || holes.Count == 0)
            return caps;

        List<float>[] cuts =
        {
            new List<float>(), new List<float>(), new List<float>()
        };
        for (int h = 0; h < holes.Count; ++h)
        {
            for (int axis = 0; axis < 3; ++axis)
            {
                cuts[axis].Add(holes[h].Min[axis]);
                cuts[axis].Add(holes[h].Max[axis]);
            }
        }

        const float epsilon = 0.00001f;
        for (int axis = 0; axis < 3; ++axis)
        {
            cuts[axis].Sort();
            for (int i = cuts[axis].Count - 1; i > 0; --i)
            {
                if (cuts[axis][i] - cuts[axis][i - 1] <= epsilon)
                    cuts[axis].RemoveAt(i);
            }
        }

        int nx = cuts[0].Count - 1;
        int ny = cuts[1].Count - 1;
        int nz = cuts[2].Count - 1;
        if (nx <= 0 || ny <= 0 || nz <= 0)
            return caps;

        bool[,,] insideUnion = new bool[nx, ny, nz];
        for (int x = 0; x < nx; ++x)
        {
            for (int y = 0; y < ny; ++y)
            {
                for (int z = 0; z < nz; ++z)
                {
                    Vector3 center = new Vector3(
                        (cuts[0][x] + cuts[0][x + 1]) * 0.5f,
                        (cuts[1][y] + cuts[1][y + 1]) * 0.5f,
                        (cuts[2][z] + cuts[2][z + 1]) * 0.5f);
                    for (int h = 0; h < holes.Count; ++h)
                    {
                        if (center.x >= holes[h].Min.x &&
                            center.x <= holes[h].Max.x &&
                            center.y >= holes[h].Min.y &&
                            center.y <= holes[h].Max.y &&
                            center.z >= holes[h].Min.z &&
                            center.z <= holes[h].Max.z)
                        {
                            insideUnion[x, y, z] = true;
                            break;
                        }
                    }
                }
            }
        }

        for (int x = 0; x < nx; ++x)
        {
            for (int y = 0; y < ny; ++y)
            {
                for (int z = 0; z < nz; ++z)
                {
                    if (!insideUnion[x, y, z])
                        continue;

                    Vector3 cellCenter = new Vector3(
                        (cuts[0][x] + cuts[0][x + 1]) * 0.5f,
                        (cuts[1][y] + cuts[1][y + 1]) * 0.5f,
                        (cuts[2][z] + cuts[2][z + 1]) * 0.5f);
                    for (int axis = 0; axis < 3; ++axis)
                    {
                        for (int direction = -1;
                             direction <= 1;
                             direction += 2)
                        {
                            int nxCell = x + (axis == 0 ? direction : 0);
                            int nyCell = y + (axis == 1 ? direction : 0);
                            int nzCell = z + (axis == 2 ? direction : 0);
                            bool neighborInside = nxCell >= 0 && nxCell < nx &&
                                nyCell >= 0 && nyCell < ny &&
                                nzCell >= 0 && nzCell < nz &&
                                insideUnion[nxCell, nyCell, nzCell];
                            if (neighborInside)
                                continue;

                            int axisCell = axis == 0 ? x : axis == 1 ? y : z;
                            float faceValue = direction > 0
                                ? cuts[axis][axisCell + 1]
                                : cuts[axis][axisCell];
                            Vector3 normal = AxisDirection(axis) * -direction;
                            if (!ShouldEmitLocalHoleUnionFace(
                                    holes, cellCenter, axis, faceValue,
                                    normal, epsilon))
                                continue;

                            int uAxis = (axis + 1) % 3;
                            int vAxis = (axis + 2) % 3;
                            int uCell = uAxis == 0 ? x : uAxis == 1 ? y : z;
                            int vCell = vAxis == 0 ? x : vAxis == 1 ? y : z;
                            Vector3 p0 = cellCenter;
                            p0[axis] = faceValue;
                            p0[uAxis] = cuts[uAxis][uCell];
                            p0[vAxis] = cuts[vAxis][vCell];
                            Vector3 p1 = p0;
                            p1[uAxis] = cuts[uAxis][uCell + 1];
                            Vector3 p2 = p1;
                            p2[vAxis] = cuts[vAxis][vCell + 1];
                            Vector3 p3 = p0;
                            p3[vAxis] = cuts[vAxis][vCell + 1];
                            AppendCarvedQuadTriangles(
                                caps, p0, p1, p2, p3, normal);
                        }
                    }
                }
            }
        }
        return caps;
    }

    private static void AppendCarvedQuadTriangles(
        List<CarveTriangle> output,
        Vector3 a,
        Vector3 b,
        Vector3 c,
        Vector3 d,
        Vector3 normal)
    {
        if (Vector3.Dot(Vector3.Cross(b - a, c - a), normal) < 0f)
        {
            Vector3 swap = b;
            b = d;
            d = swap;
        }
        output.Add(new CarveTriangle { A = a, B = b, C = c, Normal = normal });
        output.Add(new CarveTriangle { A = a, B = c, C = d, Normal = normal });
    }

    private static bool ShouldEmitLocalHoleUnionFace(
        List<PortalHole> holes,
        Vector3 cellCenter,
        int faceAxis,
        float faceValue,
        Vector3 normal,
        float epsilon)
    {
        bool insideAtLeastOneHole = false;
        bool sideBoundary = false;
        bool blindBackBoundary = false;

        for (int h = 0; h < holes.Count; ++h)
        {
            PortalHole hole = holes[h];
            if (cellCenter.x < hole.Min.x || cellCenter.x > hole.Max.x ||
                cellCenter.y < hole.Min.y || cellCenter.y > hole.Max.y ||
                cellCenter.z < hole.Min.z || cellCenter.z > hole.Max.z)
                continue;

            insideAtLeastOneHole = true;
            if (hole.Axis != faceAxis)
            {
                // A hole only has side walls on the aperture axes. A union
                // cell can also touch another hole's front/back plane here;
                // treating every non-normal axis as a side wall creates a
                // spurious cap across through-openings (often visible as a
                // generated floor when portals overlap on a carved surface).
                if (Mathf.Abs(faceValue - hole.Min[faceAxis]) <= epsilon ||
                    Mathf.Abs(faceValue - hole.Max[faceAxis]) <= epsilon)
                    sideBoundary = true;
                continue;
            }

            if (hole.Through ||
                Mathf.Abs(faceValue - hole.BackAxis) <= epsilon)
                continue;

            float backFace = hole.BackNormalSign > 0f
                ? hole.Min[faceAxis]
                : hole.Max[faceAxis];
            if (Mathf.Abs(faceValue - backFace) <= epsilon &&
                Vector3.Dot(normal,
                    AxisDirection(faceAxis) * hole.BackNormalSign) > 0.9f)
                blindBackBoundary = true;
        }

        return insideAtLeastOneHole && (sideBoundary || blindBackBoundary);
    }

