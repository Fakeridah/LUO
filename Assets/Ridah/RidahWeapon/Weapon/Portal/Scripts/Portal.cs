    // Source rebuilds the wall brush collision when a portal moves. Unity
    // cannot subtract from a primitive collider, so the host wall keeps its
    // own collider completely untouched and an extra collision-only patch is
    // generated around each portal: a five-sided blind recess that starts on
    // the traversable face and stops one player half-depth behind it. Because
    // the patch is derived from the portal quad instead of the host geometry,
    // it behaves identically for BoxCollider and MeshCollider (polygon) walls
    // and never thickens the whole wall. This is collision only: Source's
    // visible aperture is the portal quad, ring mesh and stencil mask, never a
    // rectangular hole cut into the wall renderer's MeshFilter.
    private static readonly Dictionary<GameObject, WallCarveState> CarvedWalls =
        new Dictionary<GameObject, WallCarveState>();

    // Collision patch colliders generated by CarvedWalls: the aperture sleeve
    // inside each host wall. They are ordinary solid geometry, not portal
    // walls, so the aperture filter must not touch them.
    private static readonly HashSet<Collider> PortalPatchColliders =
        new HashSet<Collider>();
    // Only cut the host wall while the Source hull is crossing the portal
    // plane. The movement sweep now teleports in the same command.
    private const float PlayerCutoutDepth = 0.05f;
    private const float PlayerCutoutMargin = 0.35f;
    private const float PlayerCutoutTolerance = 0.02f;
    // ClampCenterIntoOpening is always followed by a FitsPortalOpening check on
    // the centre it returned, and that check re-derives the offset from the
    // reconstructed point. Clamping exactly onto the boundary therefore lands a
    // hair outside after the round trip and the repair is rejected by the very
    // test that asked for it - a real case, because a portal placed with any
    // camera roll makes the hull's projected half-width land arbitrarily close
    // to the limit. Inset the clamp by a value far below any visible distance
    // so the repaired centre always verifies.
    private const float ClampVerifyInset = 0.0005f;
    // A Physics.BoxCast that begins overlapping its target reports distance 0.
    // CTrace_PlayerAABB_vs_Portals discards such a portal trace unless the
    // real-space trace was also startsolid, so this only needs to absorb
    // floating point noise on the extent-shift tangency, never proximity.
    private const float RemoteStartSolidEpsilon = 0.0001f;
    // Source values are in Hammer Units. 0.1 HU is the inverse-hole carve used
    // for the wall and entity hole; 0.65 HU = (0.1 + 1/16)*4 is the AABB angle
    // transform carve below the lower portal edge. Unity walls have no carved
    // collision, so the same allowances are applied to the aperture tests.
    private const float SourceHoleCarveHu = 0.1f;
    private const float SourceAabbCarveHu =
        (0.1f + 1f / 16f) * 4f;
    private const float SourcePortalHoleCarve =
        SourceHoleCarveHu / PortalTransformMath.HammerUnitsPerUnityUnit;
    private const float SourcePortalBottomCarve =
        SourceAabbCarveHu / PortalTransformMath.HammerUnitsPerUnityUnit;
    private const float SourcePortalQuadTestEpsilon =
        -0.03125f / PortalTransformMath.HammerUnitsPerUnityUnit;
    private const float SourcePortalQuadMargin =
        1f / PortalTransformMath.HammerUnitsPerUnityUnit;
    // prop_portal_shared.h:24-25, portal_shareddefs.h:18-19.
    private const float SourcePortalHalfWidthHu = 32f;
    private const float SourcePortalHalfHeightHu = 56f;
    private const float SourcePortalHalfDepthHu = 2f;
    // c_prop_portal.cpp skips ghosting entities whose center is more than
    // 5 Hammer units behind the entry plane.
    private const float SourceGhostBackSideLimit =
        5f / PortalTransformMath.HammerUnitsPerUnityUnit;
    // PortalSimulation.cpp builds the ghosting hole from 0.5 HU in front of
    // the entry plane through 500 HU behind it.
    private const float SourceGhostHoleFrontInset =
        0.5f / PortalTransformMath.HammerUnitsPerUnityUnit;
    private const float SourceGhostHoleDepth =
        500f / PortalTransformMath.HammerUnitsPerUnityUnit;
    private const float SourcePortalBumpForgivenessHu = 2f;
    // portalsimulation.cpp:71. Source separates the two collision halves by
    // 1/16 HU along the portal plane so the front piece and rear strips never
    // meet in a zero-thickness seam.
    private const float SourceWallSeparationHu = 1f / 16f;
    // Source player hull half-depth is 16 HU. The portal plane sits on the
    // traversable wall face, so the carve only needs a blind recess deep
    // enough to contain the hull while its centre crosses that face. Leaving
    // the opposite wall face solid is what blocks reverse entry naturally;
    // no extra back cap is needed.
    private const float SourcePlayerHalfDepthHu = 16f;
    // Source's standing hull is 32 x 72 x 32 HU, so half is 16 x 36 x 16.
    // The depth the hull has to travel past the traversable face before its
    // centre reaches the plane is its support distance along the plane
    // normal, which is the half-depth only for a wall. A floor needs the
    // half-height (36 HU) and a slope needs a blend of the two, so the recess
    // cannot be one fixed number: the old fixed 20 HU served a wall exactly
    // and starved every slope of the depth it needed.
    private const float SourcePlayerHalfWidthHu = 16f;
    private const float SourcePlayerHalfHeightHu = 36f;
    // Source's duck hull is 32 x 54 x 32 HU, so half is 16 x 27 x 16.
    // A crouched player can clear a shallower recess, which is what lets a
    // shallow surface accept a placement whose back clearance is tighter than
    // the standing hull needs.
    private const float SourcePlayerDuckHalfHeightHu = 27f;
    // cos(45 deg), with a hair of slack so an exact 45 degree surface lands on
    // the duck side instead of being decided by float rounding. A surface whose
    // normal is within this of straight up counts as a shallow slope (a floor
    // included), which is the range where the duck half-height is used for the
    // back-clearance requirement.
    private const float SourceShallowSurfaceDot = 0.707f;
    // The crossing stays a CENTRE test - the centre must reach the portal.
    // On a shallow slope the centre has to sink a whole half-height to get
    // there, which the ground prevents. Pull the test plane part-way toward
    // the player instead of all the way to the feet: 0.5 is a middle value,
    // enough to let gravity carry the hull through the plane on a slope
    // without firing the moment the feet touch it. Zero restores the exact
    // centre test; one makes it a full origin (feet) test.
    private const float SourcePortalCrossReliefFraction = 0.5f;

    // Source tests the hull centre against the *exact* exit plane, so the
    // point the player is placed at is not already "behind" the portal they
    // just left, and the portal owns the player for a moment afterwards. Our
    // centre-plane relief pulls that test plane toward the player, which
    // turns the pure-transform landing point into an immediate re-crossing
    // whenever the hull is briefly not moving (a wall exit with ~0 speed,
    // or a hull momentarily held on the exit rim). Hold the just-exited
    // portal out of crossing detection until the centre is genuinely back
    // on the traversable side of it. This is a crossing gate only - it never
    // moves the player, so the Source-style pure-transform landing stays.
    private static Portal s_recentExitPortal;
    private const float SourceExitClearanceMargin = 0.02f;
    public const float PortalableObjectExitClearance = SourceExitClearanceMargin;

    private const float SourceBlindRecessDepthHu =
        SourcePlayerHalfDepthHu + SourcePortalHalfDepthHu +
        SourcePortalBumpForgivenessHu;

    // Local collision patch tuning, in Unity units.
    //  * FrontInset keeps the patch's front and back faces just inside the
    //    host wall's own faces, so the wall always wins the first contact and
    //    the two colliders never produce coplanar duplicate planes.
    //  * HoleClearance widens the collision hole past FitsPortalOpening's
    //    tolerance, so a hull that is allowed to pass never touches the hole
    //    walls at all; the patch only acts when the hull leaves the opening.
    //  * OuterMargin sizes the solid slab around the hole.
    private const float PatchFrontInset = 0.004f;
    private const float PatchHoleClearance = 0.04f;
    private const float PatchOuterMargin = 0.12f;

