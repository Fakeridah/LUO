    private static bool ShouldIgnorePortalWallCollision(
        Collider candidate,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        Vector3 hullSweepDelta,
        bool allowApertureEdgeOverlap)
    {
        return ShouldIgnorePortalWallCollision(
            candidate,
            hullCenter,
            hullHalfExtents,
            hullRotation,
            hullSweepDelta,
            allowApertureEdgeOverlap,
            Vector3.zero,
            Vector3.up);
    }

    private static bool ShouldIgnorePortalWallCollision(
        Collider candidate,
        Vector3 hullCenter,
        Vector3 hullHalfExtents,
        Quaternion hullRotation,
        Vector3 hullSweepDelta,
        bool allowApertureEdgeOverlap,
        Vector3 duckHullHalfExtents,
        Vector3 movementUp)
    {
        if (candidate == null)
            return false;
        if (IsPortalOwnedCollider(candidate))
            return true;
        // The local collision patch is ordinary solid geometry: it is only the
        // aperture sleeve, it never leaves the host wall volume, and it is
        // never overlapped by design. Movement and stuck recovery both treat
        // it as a normal wall, so a genuine penetration can still be freed.
        if (IsPortalPatchCollider(candidate))
            return false;

        for (int i = 0; i < ActivePortals.Count; ++i)
        {
            Portal portal = ActivePortals[i];
            if (!HasActivePair(portal) ||
                (candidate != portal.wallCollider &&
                 !candidate.transform.IsChildOf(portal.wallCollider.transform)))
                continue;

            // Stuck recovery must never classify a portal wall as a stuck
            // penetration. Thin walls overlap the hull at the portal plane by
            // design, and carved walls can legitimately overlap the hull at
            // the aperture rim/top edge. Movement collision still blocks the
            // solid parts and handles sliding; letting CheckStuck also see the
            // same contact zeroes velocity every command and freezes the
            // player exactly at the edge or upper lip.
            if (allowApertureEdgeOverlap)
                return true;

            if (IsCarvedWall(portal))
            {
                WallCarveState state;
                if (CarvedWalls.TryGetValue(candidate.gameObject, out state) &&
                    state.BackCaps.Count > 0)
                {
                    for (int cap = 0; cap < state.BackCaps.Count; ++cap)
                    {
                        Portal capOwner = state.BackCaps[cap].Owner;
                        if (capOwner == null)
                            continue;
                        Vector3 planeNormal = GetPortalPlaneNormal(capOwner);
                        if (Vector3.Dot(
                                hullCenter - capOwner.transform.position,
                                planeNormal) > 0f)
                            continue;
                        // Overlapping the reverse side of a portal wall must
                        // remain solid; only the front-to-back sweep is open.
                        return false;
                    }
                }
                continue;
            }

            Vector3 apertureNormal = GetPortalPlaneNormal(portal);
            float apertureStart = Vector3.Dot(
                hullCenter - portal.transform.position, apertureNormal);
            float apertureSweep = Vector3.Dot(
                hullSweepDelta, apertureNormal);
            // Only a reverse-side hull actively sweeping toward the wall is
            // solid. A centre exactly on the portal plane with zero sweep is
            // a portal overlap, not wall penetration; treating equality as
            // reverse-side makes thin walls freeze in stuck recovery.
            if (apertureStart < 0f && apertureSweep > 0f)
                continue;

            // Stuck recovery only needs to recognise a portal-plane overlap;
            // its zero-sweep query must not reapply the movement whole-hull
            // gate, or the player freezes exactly on the portal plane.
            if (!IsPortalQuadSweepOverOpening(
                    portal, hullCenter, hullSweepDelta))
                continue;
            return true;
        }

        return false;
    }

